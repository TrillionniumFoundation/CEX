)
on conflict (policy_revision) do nothing;

select pg_catalog.setval(
    pg_catalog.pg_get_serial_sequence(
        'public.trnm_online_settlement_operator_policy_revisions',
        'policy_revision'
    ),
    (
        select max(policy_revision)
          from public.trnm_online_settlement_operator_policy_revisions
    ),
    true
);

create table if not exists public.trnm_online_settlement_operator_replay_requests (
    request_id text primary key
        check (request_id ~ '^trnm-settlement-replay-v1:[0-9a-f]{64}$'),
    contract_version text not null
        check (contract_version = 'trnm_settlement_operator_replay_v1'),
    job_id text not null
        references public.trnm_online_settlement_jobs(job_id) on delete restrict,
    capture_id text not null
        references public.trnm_online_settlement_captures(capture_id) on delete restrict,
    intent_id text not null check (btrim(intent_id) <> ''),
    intent_hash text not null check (intent_hash ~ '^[0-9a-f]{64}$'),
    remote_request_id text not null
        check (remote_request_id ~ '^trnm-settlement-remote-v1:[0-9a-f]{64}$'),
    replay_generation bigint not null check (replay_generation > 0),
    operator_id text not null
        check (btrim(operator_id) <> '' and length(operator_id) <= 256),
    change_ticket text not null
        check (change_ticket ~ '^[A-Za-z0-9][A-Za-z0-9._:/-]{2,127}$'),
    reason text not null
        check (length(btrim(reason)) between 8 and 1024),
    prior_state text not null check (prior_state = 'dead_letter'),
    prior_attempts integer not null check (prior_attempts between 0 and 16),
    prior_remote_attempts integer not null check (prior_remote_attempts between 0 and 16),
    prior_last_error text check (prior_last_error is null or length(prior_last_error) <= 1024),
    policy_revision bigint not null
        references public.trnm_online_settlement_operator_policy_revisions(policy_revision)
        on delete restrict,
    authorized_at timestamptz not null default pg_catalog.clock_timestamp(),
    retain_until timestamptz not null,
    unique (job_id, replay_generation),
    check (retain_until >= authorized_at + interval '365 days')
);

create index if not exists idx_trnm_online_settlement_operator_replay_job_v1
    on public.trnm_online_settlement_operator_replay_requests(job_id, replay_generation);

create index if not exists idx_trnm_online_settlement_operator_replay_retention_v1
    on public.trnm_online_settlement_operator_replay_requests(retain_until, authorized_at);

