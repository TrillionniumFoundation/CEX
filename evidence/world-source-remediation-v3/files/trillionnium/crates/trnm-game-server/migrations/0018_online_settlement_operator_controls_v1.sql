create or replace view public.trnm_online_settlement_operator_alerts_v1 as
with policy as (
    select *
      from public.trnm_online_settlement_operator_policy_revisions
     order by policy_revision desc
     limit 1
),
replays as (
    select
        count(*) as replay_total,
        count(*) filter (
            where authorized_at >= pg_catalog.clock_timestamp() - interval '24 hours'
        ) as replay_last_24h,
        min(retain_until) as earliest_retain_until
      from public.trnm_online_settlement_operator_replay_requests
)
select
    policy.policy_revision,
    metrics.remote_dead_letter,
    metrics.expired_leases,
    metrics.remote_pending,
    metrics.remote_retryable,
    metrics.pending_apply,
    metrics.oldest_eligible_age,
    metrics.oldest_pending_apply_age,
    replays.replay_total,
    replays.replay_last_24h,
    replays.earliest_retain_until,
    policy.dead_letter_alert_threshold,
    policy.expired_lease_alert_threshold,
    policy.oldest_eligible_alert_seconds,
    policy.oldest_pending_apply_alert_seconds,
    policy.replay_24h_alert_threshold,
    metrics.remote_dead_letter >= policy.dead_letter_alert_threshold
        as dead_letter_alert,
    metrics.expired_leases >= policy.expired_lease_alert_threshold
        as expired_lease_alert,
    coalesce(
        extract(epoch from metrics.oldest_eligible_age) >=
            policy.oldest_eligible_alert_seconds,
        false
    ) as oldest_eligible_alert,
    coalesce(
        extract(epoch from metrics.oldest_pending_apply_age) >=
            policy.oldest_pending_apply_alert_seconds,
        false
    ) as pending_apply_age_alert,
    replays.replay_last_24h >= policy.replay_24h_alert_threshold
        as replay_volume_alert
from public.trnm_online_settlement_metrics_v1 metrics
cross join policy
cross join replays;

