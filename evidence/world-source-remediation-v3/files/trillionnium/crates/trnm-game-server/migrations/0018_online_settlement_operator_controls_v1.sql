-- Audited operator controls for terminal settlement recovery.
--
-- This migration deliberately does not add a generic queue reset. A replay
-- request must bind every immutable settlement identity, may authorize only one
-- additional remote attempt, and is retained as append-only evidence.

create table if not exists public.trnm_online_settlement_operator_policy_revisions (
    policy_revision bigint generated by default as identity primary key,
    contract_version text not null
        check (contract_version = 'trnm_settlement_operator_policy_v1'),
    retention_days integer not null
        check (retention_days between 365 and 36500),
    dead_letter_alert_threshold bigint not null
        check (dead_letter_alert_threshold between 1 and 1000000),
    expired_lease_alert_threshold bigint not null
        check (expired_lease_alert_threshold between 1 and 1000000),
    oldest_eligible_alert_seconds bigint not null
        check (oldest_eligible_alert_seconds between 30 and 86400),
    oldest_pending_apply_alert_seconds bigint not null
        check (oldest_pending_apply_alert_seconds between 30 and 86400),
    replay_24h_alert_threshold bigint not null
        check (replay_24h_alert_threshold between 1 and 1000000),
    approved_by text not null
        check (btrim(approved_by) <> '' and length(approved_by) <= 256),
    change_ticket text not null
        check (change_ticket ~ '^[A-Za-z0-9][A-Za-z0-9._:/-]{2,127}$'),
    reason text not null
        check (length(btrim(reason)) between 8 and 1024),
    created_at timestamptz not null default pg_catalog.clock_timestamp()
);

insert into public.trnm_online_settlement_operator_policy_revisions (
    policy_revision,
    contract_version,
    retention_days,
    dead_letter_alert_threshold,
    expired_lease_alert_threshold,
    oldest_eligible_alert_seconds,
    oldest_pending_apply_alert_seconds,
    replay_24h_alert_threshold,
    approved_by,
    change_ticket,
    reason
) values (
    1,
    'trnm_settlement_operator_policy_v1',
    2555,
    1,
    1,
    300,
    300,
    3,
    'migration-default-candidate',
    'WORLD-P0-001',
