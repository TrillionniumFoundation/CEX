-- The initial-intent indexes are installed by the catalog-aware
-- `history_constraint_guard` below.  Keeping a raw CREATE INDEX IF NOT EXISTS
-- here would let a same-named object on another relation (or a wrong predicate)
-- be silently accepted before that guard gets a chance to inspect it.

-- A partially-applied rollout may already contain history rows.  Do not
-- silently preserve a forked intent under two receipt ids: abort the upgrade
-- before exposing a mixed authority view.  Valid legacy rows (one receipt id
-- per intent, including an authoritative NULL amount) continue through
-- backfill only when their projection identity and amount match exactly.
do $duplicate_guard$
begin
    if exists (
        select 1
          from public.league_term_exchange_receipt_events_v1
         group by intent_id
        having count(distinct receipt_id) > 1
    ) then
        raise exception 'normalized league receipt history contains multiple receipt_ids for one intent';
    end if;
    if exists (
        select 1
          from public.world_term_exchange_receipt_events_v1
         group by intent_id
