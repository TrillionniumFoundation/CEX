        raise exception 'normalized term exchange receipt event identity key is invalid';
    end if;
    if new.protocol_version is null or btrim(new.protocol_version) = ''
       or new.intent_id is null or btrim(new.intent_id) = ''
       or new.term_id is null or btrim(new.term_id) = ''
       or new.backend_id is null or btrim(new.backend_id) = ''
       or new.backend_kind is null or btrim(new.backend_kind) = '' then
        raise exception 'normalized term exchange receipt event immutable identity is blank';
    end if;
    if new.backend_kind not in ('cex', 'dex', 'chain', 'local_test', 'external') then
        raise exception 'normalized term exchange receipt event backend_kind is invalid';
    end if;
    if new.status is null or length(btrim(new.status)) not between 1 and 128
       or new.progression_class is null
       or new.progression_class not in (
           'progression_allowed', 'recoverable_hold', 'terminal_skip', 'hard_fail'
       ) then
        raise exception 'normalized term exchange receipt event status/progression is invalid';
    end if;
    if new.event_kind is null
       or new.event_kind not in ('initial', 'backfill', 'hold', 'final', 'transition') then
        raise exception 'normalized term exchange receipt event kind is invalid';
    end if;
    if new.receipt_hash is null
       or new.receipt_hash !~ '^sha256:[0-9a-f]{64}$'
       or (new.previous_receipt_hash is not null
           and new.previous_receipt_hash !~ '^sha256:[0-9a-f]{64}$') then
        raise exception 'normalized term exchange receipt event hash shape is invalid';
    end if;
    if new.amount_credits is not null and new.amount_credits < 0 then
        raise exception 'normalized term exchange receipt event amount is invalid';
    end if;
    if new.finalized_at is null or new.created_at is null then
        raise exception 'normalized term exchange receipt event timestamp is NULL';
    end if;
        if new.receipt_json is null or jsonb_typeof(new.receipt_json) <> 'object' then
            raise exception 'normalized term exchange receipt event JSON must be an object';
        end if;
        if new.receipt_id is null or btrim(new.receipt_id) = '' then
            raise exception 'normalized term exchange receipt event receipt_id must be non-empty';
        end if;

        -- Do not rely on `->>` alone: it stringifies numeric JSON values and
        -- could make a non-serde-compatible receipt appear equal to the typed
        -- SQL columns.  Required EconomicReceipt strings must be JSON strings;
        -- optional string fields may be absent/JSON null, but never numbers,
        -- arrays or objects.
        if jsonb_typeof(new.receipt_json -> 'protocol_version') is distinct from 'string'
           or jsonb_typeof(new.receipt_json -> 'receipt_id') is distinct from 'string'
           or jsonb_typeof(new.receipt_json -> 'intent_id') is distinct from 'string'
           or jsonb_typeof(new.receipt_json -> 'term_id') is distinct from 'string'
           or jsonb_typeof(new.receipt_json -> 'backend_id') is distinct from 'string'
           or jsonb_typeof(new.receipt_json -> 'backend_kind') is distinct from 'string'
           or jsonb_typeof(new.receipt_json -> 'status') is distinct from 'string'
           or jsonb_typeof(new.receipt_json -> 'progression_class') is distinct from 'string'
           or (new.receipt_json ? 'settlement_reference'
               and jsonb_typeof(new.receipt_json -> 'settlement_reference') is distinct from 'null'
               and jsonb_typeof(new.receipt_json -> 'settlement_reference') <> 'string')
           or (new.receipt_json ? 'ledger_entry_id'
               and jsonb_typeof(new.receipt_json -> 'ledger_entry_id') is distinct from 'null'
               and jsonb_typeof(new.receipt_json -> 'ledger_entry_id') <> 'string')
           or (new.receipt_json ? 'reason'
               and jsonb_typeof(new.receipt_json -> 'reason') is distinct from 'null'
               and jsonb_typeof(new.receipt_json -> 'reason') <> 'string') then
            raise exception 'normalized term exchange receipt event JSON typed field mismatch';
        end if;
        if not (new.receipt_json ? 'finalized_at_epoch')
           or jsonb_typeof(new.receipt_json -> 'finalized_at_epoch') is distinct from 'number'
           or (new.receipt_json ->> 'finalized_at_epoch') !~ '^-?[0-9]+$'
           or (new.receipt_json ->> 'finalized_at_epoch')::numeric
                is distinct from (extract(epoch from new.finalized_at)::bigint)::numeric then
            raise exception 'normalized term exchange receipt event finalized_at_epoch is invalid';
        end if;

    -- Serialize all writers for one receipt identity before reading the
    -- predecessor.  The generated repository shadow SQL takes the same
    -- table-qualified lock; taking it here as well closes the race for direct
    -- SQL writers and remains re-entrant for callers that already hold it.
    perform pg_advisory_xact_lock(
        hashtextextended(
            format(
                'cex:term-exchange-receipt-event:%s:%s',
                tg_table_name,
                new.receipt_id
            ),
            0
        )
    );

    if new.receipt_json ->> 'protocol_version' is distinct from new.protocol_version
       or new.receipt_json ->> 'receipt_id' is distinct from new.receipt_id
       or new.receipt_json ->> 'intent_id' is distinct from new.intent_id
       or new.receipt_json ->> 'term_id' is distinct from new.term_id
       or new.receipt_json ->> 'backend_id' is distinct from new.backend_id
       or new.receipt_json ->> 'backend_kind' is distinct from new.backend_kind
       or new.receipt_json ->> 'status' is distinct from new.status
       or new.receipt_json ->> 'progression_class' is distinct from new.progression_class
       or new.receipt_json ->> 'settlement_reference' is distinct from new.settlement_reference
       or new.receipt_json ->> 'ledger_entry_id' is distinct from new.ledger_entry_id
       or new.receipt_json ->> 'reason' is distinct from new.reason
       -- JSONB represents an explicit JSON null as the jsonb value `null`,
       -- whereas to_jsonb(NULL::bigint) is SQL NULL.  Normalize both sides
       -- so legacy projections with an unknown amount can be backfilled and
       -- remain fail-closed at value-authority callers.
       or jsonb_typeof(new.receipt_json -> 'amount_credits') is distinct from
          (case when new.amount_credits is null then 'null' else 'number' end)
       or (new.receipt_json ->> 'amount_credits') !~ '^-?[0-9]+$'
       or coalesce(new.receipt_json -> 'amount_credits', 'null'::jsonb)
          is distinct from coalesce(to_jsonb(new.amount_credits), 'null'::jsonb)
       or new.receipt_json ->> 'finalized_at_epoch' is distinct from
          (extract(epoch from new.finalized_at)::bigint)::text then
        raise exception 'normalized term exchange receipt event JSON binding mismatch';
    end if;

    -- When this game receipt is also backed by a durable native intent, the
    -- immutable intent amount is the only value authority.  The native intent
    -- amount is optional for audit-only commands; a present value (including
    -- JSON null) must be a non-negative JSON integer.  Invalid/negative/null
    -- intent amounts fail closed: they may only produce a NULL/zero
    -- projection, never a positive amount.  An omitted key alone leaves the
    -- nullable legacy projection amount authoritative.
    select exists (
        select 1
          from public.trnm_economic_intents
         where intent_id = new.intent_id
    ) into intent_found;
    if intent_found then
        select intent_json -> 'amount_credits' as amount_json
          into intent_amount_json
          from public.trnm_economic_intents
         where intent_id = new.intent_id;
    end if;
    -- `->` yields SQL NULL only for an omitted key; JSONB `null` is still a
    -- present immutable value and must enter the invalid/fail-closed branch.
    if intent_found and intent_amount_json is not null then
        immutable_amount_present := true;
        if jsonb_typeof(intent_amount_json) <> 'number'
           or (intent_amount_json #>> '{}') !~ '^-?[0-9]+$' then
            immutable_amount_invalid := true;
        else
            begin
                immutable_amount := (intent_amount_json #>> '{}')::bigint;
            exception when others then
                immutable_amount_invalid := true;
            end;
            if immutable_amount is null or immutable_amount < 0 then
                immutable_amount_invalid := true;
            end if;
        end if;
    end if;
    if immutable_amount_invalid then
        if new.amount_credits is not null and new.amount_credits <> 0 then
            raise exception 'normalized receipt amount is not authorized by an invalid immutable intent amount';
        end if;
    elsif immutable_amount_present
          and new.amount_credits is distinct from immutable_amount then
        raise exception 'normalized receipt amount does not match immutable intent amount';
    end if;

    -- A receipt id is the intent-level retry identity.  Check by intent_id in
    -- addition to the receipt-id hash-chain lookup below; otherwise a caller
    -- could fork one intent into two independent receipt histories.  The
    -- projection check closes the first-event gap when a projection row was
    -- written before its history row during a partial rollout.
    execute format(
        'select event_id, receipt_id, event_sequence, amount_credits
           from public.%I
          where intent_id = $1
          order by event_sequence desc, event_id desc
          limit 1',
        tg_table_name
    )
    into latest_intent_event
    using new.intent_id;
    if latest_intent_event.event_id is not null then
        if new.receipt_id is distinct from latest_intent_event.receipt_id then
            raise exception 'normalized receipt_id must remain stable for an intent';
        end if;
        if latest_intent_event.amount_credits is not null
           and new.amount_credits is distinct from latest_intent_event.amount_credits then
            raise exception 'normalized receipt amount must remain stable for an intent';
        end if;
    end if;

    projection_table := case tg_table_name
        when 'league_term_exchange_receipt_events_v1' then 'league_term_exchange_receipts'
        when 'world_term_exchange_receipt_events_v1' then 'world_term_exchange_receipts'
        else null
    end;
    if projection_table is not null then
        -- Every normalized history event is an append-only audit projection of
        -- exactly one compatibility receipt row.  Resolve that authority by
        -- receipt_id (never by intent_id): otherwise a forged event can pick a
        -- different receipt's projection, or become self-authenticated when
        -- no projection exists at all.
        execute format(
            'select exists (
                 select 1
                   from public.%I
                  where receipt_id = $1
             )',
            projection_table
        )
        into projection_found
        using new.receipt_id;
        if not projection_found then
            raise exception 'normalized receipt event projection authority is missing';
        end if;

        execute format(
            'select receipt_id, protocol_version, intent_id, term_id,
                    backend_id, backend_kind, amount_credits
               from public.%I
              where receipt_id = $1',
            projection_table
        )
        into projection_row
        using new.receipt_id;
        -- The lookup above is keyed by the new receipt id.  Use the same key
        -- here rather than trusting the caller-provided intent id; a mismatch
        -- must fail even when another projection happens to use that intent.
        if projection_row.receipt_id is distinct from new.receipt_id
           or projection_row.protocol_version is distinct from new.protocol_version
           or projection_row.intent_id is distinct from new.intent_id
           or projection_row.term_id is distinct from new.term_id
           or projection_row.backend_id is distinct from new.backend_id
           or projection_row.backend_kind is distinct from new.backend_kind then
            raise exception 'normalized receipt event conflicts with immutable projection identity';
        end if;
        -- Amount is an exact nullable value, not a one-way "known value" hint:
        -- NULL is authoritative and may not be upgraded by an event carrying a
        -- positive amount, nor may a known projection be erased to NULL.
        if projection_row.amount_credits is distinct from new.amount_credits then
            raise exception 'normalized receipt amount conflicts with immutable projection amount';
        end if;

        -- An intent may not fan out to multiple compatibility receipts in one
        -- lane.  Checking this separately catches a caller that creates a new
        -- projection for an existing intent and then appends a seemingly valid
        -- event to that second receipt.
        execute format(
            'select exists (
                 select 1
                   from public.%I
                  where intent_id = $1
                    and receipt_id <> $2
             )',
            projection_table
        )
        into conflicting_projection
        using new.intent_id, new.receipt_id;
        if conflicting_projection then
            raise exception 'normalized receipt intent is bound to multiple projection receipt_ids';
        end if;
    end if;

    if new.receipt_hash is distinct from
       'sha256:' || encode(digest(new.receipt_json::text, 'sha256'), 'hex') then
        raise exception 'normalized term exchange receipt event hash mismatch';
    end if;

    execute format(
        'select event_id, event_sequence, receipt_hash,
                protocol_version, intent_id, term_id, backend_id, backend_kind,
                progression_class, amount_credits
           from public.%I
          where receipt_id = $1
          order by event_sequence desc, event_id desc
          limit 1',
        tg_table_name
    )
    into latest_event
    using new.receipt_id;

    -- `EXECUTE ... INTO` does not provide a reliable `FOUND` value across
    -- PostgreSQL versions when the target is a record.  The primary key is
    -- non-null for every real predecessor, so inspect the record field
    -- directly to distinguish the first event from an append.
    if latest_event.event_id is null then
        if new.event_sequence <> 1 or new.previous_receipt_hash is not null then
            raise exception 'first normalized term exchange receipt event must start sequence one';
        end if;
        if new.event_kind not in ('initial', 'backfill') then
            raise exception 'first normalized term exchange receipt event must be initial or backfill';
        end if;
    else
        -- A receipt id is the retry identity.  Its immutable protocol/intent
        -- binding may not change between a hold and a later final snapshot;
        -- only outcome fields (status, reason, ledger entry, amount evidence)
        -- are allowed to evolve.  This closes the otherwise silent
        -- ON-CONFLICT/append path that could attach a different intent to an
        -- existing receipt id.
        if new.protocol_version is distinct from latest_event.protocol_version
           or new.intent_id is distinct from latest_event.intent_id
           or new.term_id is distinct from latest_event.term_id
           or new.backend_id is distinct from latest_event.backend_id
           or new.backend_kind is distinct from latest_event.backend_kind then
            raise exception 'normalized term exchange receipt event immutable identity mismatch';
        end if;
        -- Amount is immutable across the append chain in both directions:
        -- NULL is a real legacy authority value, not permission to introduce
        -- a later known amount, and a known amount may not be erased.
        if new.amount_credits is distinct from latest_event.amount_credits then
            raise exception 'normalized term exchange receipt amount chain mismatch';
        end if;
        -- Only a recoverable hold is retryable.  Allowed, skipped, and hard
        -- fail classes are terminal for this receipt identity and must never
        -- be followed by a later hold/final transition.
        if latest_event.progression_class is distinct from 'recoverable_hold' then
            raise exception 'normalized terminal receipt event cannot append after final progression';
        end if;
        if latest_event.event_sequence = 9223372036854775807 then
            raise exception 'normalized term exchange receipt event sequence is exhausted';
        end if;
        if new.event_sequence <> latest_event.event_sequence + 1 then
            raise exception 'normalized term exchange receipt event sequence must append contiguously';
        end if;
        if new.previous_receipt_hash is distinct from latest_event.receipt_hash then
            raise exception 'normalized term exchange receipt event hash chain mismatch';
        end if;
        if new.event_kind in ('initial', 'backfill') then
            raise exception 'normalized term exchange receipt retry cannot be initial/backfill';
        end if;
    end if;

    if (case
            when new.status in (
                'reserved', 'settled', 'reopened_settled', 'consumed', 'refunded',
                'seller_chargeback_reserved', 'seller_chargeback_consumed',
                'approved_release', 'duplicate'
            ) then 'progression_allowed'
            when new.status in (
                'skipped_zero_price', 'skipped_zero_reward', 'skipped_zero_seller_net'
            ) then 'terminal_skip'
            when new.status in (
                'held_review', 'skipped_missing_room', 'failed_network', 'failed_identity',
                'failed_ledger', 'seller_chargeback_reserve_failed',
                'seller_chargeback_failed', 'rejected_refund_failed',
                'cancelled_refund_failed'
            ) then 'recoverable_hold'
            when new.status in (
                'failed_bad_response', 'skipped_missing_account',
                'skipped_missing_ledger_token', 'missing_account', 'missing_ledger_token'
            ) then 'hard_fail'
            else null
        end) is distinct from new.progression_class then
        raise exception 'normalized receipt status/progression mapping mismatch';
    end if;

    return new;
end
$function$;

