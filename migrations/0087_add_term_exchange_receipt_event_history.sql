$duplicate_guard$;

-- A table can have been created and populated before this migration's trigger
-- statement committed (for example, a deployment runner that executed each
-- statement independently).  INSERT triggers do not inspect rows that already
-- exist, so treating those rows as trusted would let a forged event become the
-- predecessor for every later append.  Validate the complete pre-existing
-- stream before installing the trigger/backfill path.  This is intentionally an
-- explicit, temporary DO helper rather than a persistent runtime function: the
-- only rows it can inspect are the two allow-listed history tables below.
--
-- The amount rule mirrors the INSERT trigger.  A valid immutable intent amount
-- is authoritative; an invalid/negative present intent amount may only be
-- represented by NULL/zero.  An omitted intent amount leaves a legacy unknown
-- amount as NULL; an explicit JSON null is present-but-invalid and therefore
-- may only be represented by NULL/zero.  In particular, this pass never
-- fabricates a value for a legacy NULL projection.  Every pre-existing row
-- must also bind strictly (including NULL equality) to its receipt projection
-- before the projection-first backfill inserts sequence one.
do $preexisting_history_guard$
declare
    table_spec record;
    event_row record;
    intent_row record;
    previous_receipt_id text;
    previous_receipt_hash text;
    previous_protocol_version text;
    previous_intent_id text;
    previous_term_id text;
    previous_backend_id text;
    previous_backend_kind text;
    previous_progression_class text;
    previous_event_sequence bigint;
    previous_amount_credits bigint;
    have_previous boolean;
    receipt_fork boolean;
    intent_found boolean;
    projection_found boolean;
    immutable_amount bigint;
    immutable_amount_present boolean;
    immutable_amount_invalid boolean;
    projection_row record;
    event_amount_json jsonb;
    event_amount_text text;
    expected_hash text;
    expected_progression text;
begin
    for table_spec in
        select *
          from (values
              ('league_term_exchange_receipt_events_v1'::text, 'league_term_exchange_receipts'::text, 'league'::text),
              ('world_term_exchange_receipt_events_v1'::text, 'world_term_exchange_receipts'::text, 'world'::text)
          ) as allowed_tables(history_table, projection_table, label)
    loop
        -- One receipt id is one retry identity.  A pre-existing table without
        -- the canonical uniqueness/index guards must not be allowed to bind it
        -- to two different intents.
        execute format(
            'select exists (
                 select 1
                   from public.%I
                  group by receipt_id
                 having count(distinct intent_id) > 1
             )',
            table_spec.history_table
        )
        into receipt_fork;
        if receipt_fork then
            raise exception
                'normalized % receipt history failed pre-existing-row validation: receipt_id binds multiple intents',
                table_spec.label;
        end if;

        have_previous := false;
        previous_receipt_id := null;
        previous_receipt_hash := null;
        previous_protocol_version := null;
        previous_intent_id := null;
        previous_term_id := null;
        previous_backend_id := null;
        previous_backend_kind := null;
        previous_progression_class := null;
        previous_event_sequence := null;
        previous_amount_credits := null;

        -- The event_id tie-breaker makes validation deterministic even when a
        -- partially-created table has not yet installed its identity default.
        for event_row in execute format(
            'select event_id, receipt_id, event_sequence, event_kind,
                    previous_receipt_hash, protocol_version, intent_id, term_id,
                    backend_id, backend_kind, status, progression_class,
                    settlement_reference, ledger_entry_id, reason,
                    amount_credits, finalized_at, receipt_json, receipt_hash,
                    created_at
               from public.%I
              order by receipt_id, event_sequence, event_id',
            table_spec.history_table
        )
        loop
            -- Re-check the shape constraints explicitly.  CREATE TABLE IF NOT
            -- EXISTS does not retrofit checks onto a table left by an earlier
            -- partial attempt, and a NULL SQL predicate would otherwise make a
            -- malformed legacy row look like a pass.
            if event_row.event_id is null or event_row.event_id <= 0 then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: event_id is invalid',
                    table_spec.label;
            end if;
            if event_row.receipt_id is null or btrim(event_row.receipt_id) = '' then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: receipt_id is blank',
                    table_spec.label;
            end if;
            if event_row.event_sequence is null or event_row.event_sequence <= 0 then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: event_sequence is invalid',
                    table_spec.label;
            end if;
            if event_row.event_kind is null
               or event_row.event_kind not in ('initial', 'backfill', 'hold', 'final', 'transition') then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: event_kind is invalid',
                    table_spec.label;
            end if;
            if event_row.previous_receipt_hash is not null
               and event_row.previous_receipt_hash !~ '^sha256:[0-9a-f]{64}$' then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: previous_receipt_hash is invalid',
                    table_spec.label;
            end if;
            if event_row.receipt_hash is null
               or event_row.receipt_hash !~ '^sha256:[0-9a-f]{64}$' then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: receipt_hash is invalid',
                    table_spec.label;
            end if;
            if event_row.protocol_version is null or btrim(event_row.protocol_version) = ''
               or event_row.intent_id is null or btrim(event_row.intent_id) = ''
               or event_row.term_id is null or btrim(event_row.term_id) = ''
               or event_row.backend_id is null or btrim(event_row.backend_id) = ''
               or event_row.backend_kind is null or btrim(event_row.backend_kind) = '' then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: immutable identity is blank',
                    table_spec.label;
            end if;
            if event_row.backend_kind not in ('cex', 'dex', 'chain', 'local_test', 'external') then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: backend_kind is unknown',
                    table_spec.label;
            end if;
            if event_row.status is null
               or length(btrim(event_row.status)) not between 1 and 128 then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: status is invalid',
                    table_spec.label;
            end if;
            if event_row.progression_class is null
               or event_row.progression_class not in (
                   'progression_allowed', 'recoverable_hold', 'terminal_skip', 'hard_fail'
               ) then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: progression_class is invalid',
                    table_spec.label;
            end if;
            if event_row.amount_credits is not null and event_row.amount_credits < 0 then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: amount_credits is negative',
                    table_spec.label;
            end if;
            if event_row.finalized_at is null or event_row.created_at is null then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: timestamp is NULL',
                    table_spec.label;
            end if;
            if event_row.receipt_json is null
               or jsonb_typeof(event_row.receipt_json) <> 'object' then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: receipt_json is not an object',
                    table_spec.label;
            end if;

            -- `->>` stringifies JSON scalars.  Comparing only that text would
            -- therefore accept an integer/object-shaped authority such as
            -- `intent_id: 123` when the SQL column contains `'123'`, even
            -- though the EconomicReceipt contract requires a JSON string.
            if jsonb_typeof(event_row.receipt_json -> 'protocol_version') is distinct from 'string'
               or jsonb_typeof(event_row.receipt_json -> 'receipt_id') is distinct from 'string'
               or jsonb_typeof(event_row.receipt_json -> 'intent_id') is distinct from 'string'
               or jsonb_typeof(event_row.receipt_json -> 'term_id') is distinct from 'string'
               or jsonb_typeof(event_row.receipt_json -> 'backend_id') is distinct from 'string'
               or jsonb_typeof(event_row.receipt_json -> 'backend_kind') is distinct from 'string'
               or jsonb_typeof(event_row.receipt_json -> 'status') is distinct from 'string'
               or jsonb_typeof(event_row.receipt_json -> 'progression_class') is distinct from 'string'
               or (event_row.receipt_json ? 'settlement_reference'
                   and jsonb_typeof(event_row.receipt_json -> 'settlement_reference') is distinct from 'null'
                   and jsonb_typeof(event_row.receipt_json -> 'settlement_reference') <> 'string')
               or (event_row.receipt_json ? 'ledger_entry_id'
                   and jsonb_typeof(event_row.receipt_json -> 'ledger_entry_id') is distinct from 'null'
                   and jsonb_typeof(event_row.receipt_json -> 'ledger_entry_id') <> 'string')
               or (event_row.receipt_json ? 'reason'
                   and jsonb_typeof(event_row.receipt_json -> 'reason') is distinct from 'null'
                   and jsonb_typeof(event_row.receipt_json -> 'reason') <> 'string') then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: JSON typed field mismatch',
                    table_spec.label;
            end if;

            -- Required JSON bindings are compared as typed values.  Optional
            -- fields intentionally use ->> so an absent/JSON-null value remains
            -- the same SQL NULL as the corresponding Option<String> column.
            if event_row.receipt_json ->> 'protocol_version' is distinct from event_row.protocol_version
               or event_row.receipt_json ->> 'receipt_id' is distinct from event_row.receipt_id
               or event_row.receipt_json ->> 'intent_id' is distinct from event_row.intent_id
               or event_row.receipt_json ->> 'term_id' is distinct from event_row.term_id
               or event_row.receipt_json ->> 'backend_id' is distinct from event_row.backend_id
               or event_row.receipt_json ->> 'backend_kind' is distinct from event_row.backend_kind
               or event_row.receipt_json ->> 'status' is distinct from event_row.status
               or event_row.receipt_json ->> 'progression_class' is distinct from event_row.progression_class
               or event_row.receipt_json ->> 'settlement_reference' is distinct from event_row.settlement_reference
               or event_row.receipt_json ->> 'ledger_entry_id' is distinct from event_row.ledger_entry_id
               or event_row.receipt_json ->> 'reason' is distinct from event_row.reason
               or event_row.receipt_json ->> 'finalized_at_epoch' is distinct from
                  (extract(epoch from event_row.finalized_at)::bigint)::text then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: JSON identity binding mismatch',
                    table_spec.label;
            end if;
            if not (event_row.receipt_json ? 'finalized_at_epoch')
               or jsonb_typeof(event_row.receipt_json -> 'finalized_at_epoch') is distinct from 'number'
               or (event_row.receipt_json ->> 'finalized_at_epoch') !~ '^-?[0-9]+$'
               or (event_row.receipt_json ->> 'finalized_at_epoch')::numeric
                    is distinct from (extract(epoch from event_row.finalized_at)::bigint)::numeric then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: finalized_at_epoch is invalid',
                    table_spec.label;
            end if;

            event_amount_json := event_row.receipt_json -> 'amount_credits';
            if jsonb_typeof(event_amount_json) is distinct from
                   (case when event_row.amount_credits is null then 'null' else 'number' end) then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: JSON amount nullability mismatch',
                    table_spec.label;
            end if;
            if event_row.amount_credits is not null then
                event_amount_text := event_row.receipt_json ->> 'amount_credits';
                if event_amount_text is null
                   or event_amount_text !~ '^-?[0-9]+$'
                   or event_amount_json is distinct from to_jsonb(event_row.amount_credits) then
                    raise exception
                        'normalized % receipt history failed pre-existing-row validation: JSON amount binding mismatch',
                        table_spec.label;
                end if;
            end if;

            expected_hash := 'sha256:' || encode(
                digest(event_row.receipt_json::text, 'sha256'), 'hex'
            );
            if event_row.receipt_hash is distinct from expected_hash then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: receipt_hash digest mismatch',
                    table_spec.label;
            end if;

            -- Apply the same immutable-intent amount authority as the INSERT
            -- trigger, but parse legacy JSON inside a nested exception block so
            -- an overflowing/corrupt intent becomes a fail-closed zero rule
            -- rather than aborting with an unhelpful bigint cast error.
            immutable_amount := null;
            immutable_amount_present := false;
            immutable_amount_invalid := false;
            select exists (
                select 1
                  from public.trnm_economic_intents
                 where intent_id = event_row.intent_id
            ) into intent_found;
            if intent_found then
                select intent_json -> 'amount_credits' as amount_json
                  into intent_row
                  from public.trnm_economic_intents
                 where intent_id = event_row.intent_id;
                -- `->` returns SQL NULL only when the key is absent.  A JSONB
                -- null is a present, invalid immutable amount and must not be
                -- mistaken for the audit-only omitted-key shape.
                if intent_row.amount_json is not null then
                    immutable_amount_present := true;
                    if jsonb_typeof(intent_row.amount_json) <> 'number'
                       or (intent_row.amount_json #>> '{}') !~ '^-?[0-9]+$' then
                        immutable_amount_invalid := true;
                    else
                        begin
                            immutable_amount := (intent_row.amount_json #>> '{}')::bigint;
                        exception when others then
                            immutable_amount_invalid := true;
                        end;
                        if immutable_amount is null or immutable_amount < 0 then
                            immutable_amount_invalid := true;
                        end if;
                    end if;
                end if;
            end if;
            if immutable_amount_invalid then
                if event_row.amount_credits is not null and event_row.amount_credits <> 0 then
                    raise exception
                        'normalized % receipt history failed pre-existing-row validation: amount is not authorized by invalid immutable intent',
                        table_spec.label;
                end if;
            elsif immutable_amount_present
                  and event_row.amount_credits is distinct from immutable_amount then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: amount does not match immutable intent',
                    table_spec.label;
            end if;

            -- Every legacy term history row must bind to the compatibility
            -- projection by receipt_id.  A native intent is an additional
            -- amount authority, never a substitute for the projection row:
            -- accepting a native-intent-only stream would permit a forged
            -- receipt id to become the predecessor for future retries.
            execute format(
                'select exists (
                     select 1
                       from public.%I
                      where receipt_id = $1
                 )',
                table_spec.projection_table
            )
            into projection_found
            using event_row.receipt_id;
            if not projection_found then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: no immutable intent or projection authority',
                    table_spec.label;
            end if;

            execute format(
                'select receipt_id, protocol_version, intent_id, term_id,
                        backend_id, backend_kind, amount_credits
                   from public.%I
                  where receipt_id = $1',
                table_spec.projection_table
            )
            into projection_row
            using event_row.receipt_id;
            if projection_row.receipt_id is distinct from event_row.receipt_id
               or projection_row.protocol_version is distinct from event_row.protocol_version
               or projection_row.intent_id is distinct from event_row.intent_id
               or projection_row.term_id is distinct from event_row.term_id
               or projection_row.backend_id is distinct from event_row.backend_id
               or projection_row.backend_kind is distinct from event_row.backend_kind then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: projection identity binding mismatch',
                    table_spec.label;
            end if;
            -- NULL is a real legacy authority value.  Do not upgrade it (or
            -- erase a known value) while importing a pre-existing stream.
            if projection_row.amount_credits is distinct from event_row.amount_credits then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: projection amount binding mismatch',
                    table_spec.label;
            end if;

            execute format(
                'select exists (
                     select 1
                       from public.%I
                      where intent_id = $1
                        and receipt_id <> $2
                 )',
                table_spec.projection_table
            )
            into receipt_fork
            using event_row.intent_id, event_row.receipt_id;
            if receipt_fork then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: intent has multiple projection receipt_ids',
                    table_spec.label;
            end if;

            -- Validate sequence one, contiguous appends, immutable identity,
            -- predecessor hash and terminal-state behavior exactly as the
            -- trigger does for new rows.
            if not have_previous
               or event_row.receipt_id is distinct from previous_receipt_id then
                if event_row.event_sequence <> 1
                   or event_row.previous_receipt_hash is not null
                   or event_row.event_kind not in ('initial', 'backfill') then
                    raise exception
                        'normalized % receipt history failed pre-existing-row validation: first event is not a valid sequence-one seed',
                        table_spec.label;
                end if;
                have_previous := true;
            else
                if previous_event_sequence = 9223372036854775807
                   or event_row.event_sequence <> previous_event_sequence + 1 then
                    raise exception
                        'normalized % receipt history failed pre-existing-row validation: event sequence is not contiguous',
                        table_spec.label;
                end if;
                if event_row.previous_receipt_hash is distinct from previous_receipt_hash then
                    raise exception
                        'normalized % receipt history failed pre-existing-row validation: hash chain predecessor mismatch',
                        table_spec.label;
                end if;
                if previous_progression_class is distinct from 'recoverable_hold' then
                    raise exception
                        'normalized % receipt history failed pre-existing-row validation: terminal event has a successor',
                        table_spec.label;
                end if;
                if event_row.event_kind in ('initial', 'backfill') then
                    raise exception
                        'normalized % receipt history failed pre-existing-row validation: retry event is marked initial/backfill',
                        table_spec.label;
                end if;
                if event_row.protocol_version is distinct from previous_protocol_version
                   or event_row.intent_id is distinct from previous_intent_id
                   or event_row.term_id is distinct from previous_term_id
                   or event_row.backend_id is distinct from previous_backend_id
                   or event_row.backend_kind is distinct from previous_backend_kind then
                    raise exception
                        'normalized % receipt history failed pre-existing-row validation: immutable identity changed across chain',
                        table_spec.label;
                end if;
                -- Amount is part of the immutable receipt identity.  SQL NULL
                -- is an authoritative legacy value, not a wildcard that a
                -- later retry may replace with a known amount (or erase).
                if event_row.amount_credits is distinct from previous_amount_credits then
                    raise exception
                        'normalized % receipt history failed pre-existing-row validation: amount changed across chain',
                        table_spec.label;
                end if;
            end if;

            expected_progression := case
                when event_row.status in (
                    'reserved', 'settled', 'reopened_settled', 'consumed', 'refunded',
                    'seller_chargeback_reserved', 'seller_chargeback_consumed',
                    'approved_release', 'duplicate'
                ) then 'progression_allowed'
                when event_row.status in (
                    'skipped_zero_price', 'skipped_zero_reward', 'skipped_zero_seller_net'
                ) then 'terminal_skip'
                when event_row.status in (
                    'held_review', 'skipped_missing_room', 'failed_network', 'failed_identity',
                    'failed_ledger', 'seller_chargeback_reserve_failed',
                    'seller_chargeback_failed', 'rejected_refund_failed',
                    'cancelled_refund_failed'
                ) then 'recoverable_hold'
                when event_row.status in (
                    'failed_bad_response', 'skipped_missing_account',
                    'skipped_missing_ledger_token', 'missing_account', 'missing_ledger_token'
                ) then 'hard_fail'
                else null
            end;
            if expected_progression is null
               or expected_progression is distinct from event_row.progression_class then
                raise exception
                    'normalized % receipt history failed pre-existing-row validation: status/progression mapping mismatch',
                    table_spec.label;
            end if;

            previous_receipt_id := event_row.receipt_id;
            previous_receipt_hash := event_row.receipt_hash;
            previous_protocol_version := event_row.protocol_version;
            previous_intent_id := event_row.intent_id;
            previous_term_id := event_row.term_id;
            previous_backend_id := event_row.backend_id;
            previous_backend_kind := event_row.backend_kind;
            previous_progression_class := event_row.progression_class;
            previous_event_sequence := event_row.event_sequence;
            previous_amount_credits := event_row.amount_credits;
        end loop;
    end loop;
end
$preexisting_history_guard$;

-- Promote the validated row shape to structural NOT NULL constraints.  The
-- canonical CREATE TABLE statements already declare these columns required,
-- but an interrupted runner can leave an empty or populated partial table
-- with nullable definitions.  Do this only after the pre-existing-row audit so
-- a malformed legacy row fails with the explicit authority error above rather
-- than being silently coerced.
do $history_notnull_guard$
declare
    table_spec record;
    column_name text;
    column_notnull boolean;
begin
    for table_spec in
        select *
          from (values
              ('league_term_exchange_receipt_events_v1'::text, 'league'::text),
              ('world_term_exchange_receipt_events_v1'::text, 'world'::text)
          ) as allowed_tables(history_table, label)
    loop
        foreach column_name in array array[
            'event_id', 'receipt_id', 'event_sequence', 'event_kind',
            'protocol_version', 'intent_id', 'term_id', 'backend_id',
            'backend_kind', 'status', 'progression_class', 'finalized_at',
            'receipt_json', 'receipt_hash', 'created_at'
        ]::text[]
        loop
            select a.attnotnull
              into column_notnull
              from pg_catalog.pg_attribute a
             where a.attrelid = to_regclass('public.' || table_spec.history_table)
               and a.attname = column_name
               and not a.attisdropped;
            if not found then
                raise exception
                    'normalized % receipt history required column is missing: %',
                    table_spec.label, column_name;
            end if;
            if not column_notnull then
                execute format(
                    'alter table public.%I alter column %I set not null',
                    table_spec.history_table, column_name
                );
            end if;
        end loop;
    end loop;
end
$history_notnull_guard$;

-- The row validator and NOT NULL promotion above establish value safety, but
-- they do not prove that a same-named column has the published catalog shape.
-- `CREATE TABLE IF NOT EXISTS` leaves wrong types, generated columns, and
-- defaults untouched.  Audit every column before installing the append trigger;
-- repair only the omitted defaults used by runtime INSERT paths, and reject a
-- present-but-different expression or any extra column.
do $history_catalog_shape_guard$
declare
    table_spec record;
    history_oid oid;
    relation_kind text;
    relation_persistence text;
    relation_is_partition boolean;
    actual_column_count integer;
    column_spec record;
    column_type oid;
    column_notnull boolean;
    column_identity text;
    column_generated text;
    column_default text;
    column_default_oid oid;
    normalized_default text;
    expected_columns constant integer := 20;
begin
    for table_spec in
        select *
          from (values
              ('league_term_exchange_receipt_events_v1'::text, 'league'::text),
              ('world_term_exchange_receipt_events_v1'::text, 'world'::text)
          ) as allowed_tables(history_table, label)
    loop
        history_oid := to_regclass('public.' || table_spec.history_table);
        select c.relkind::text, c.relpersistence::text, c.relispartition
          into relation_kind, relation_persistence, relation_is_partition
          from pg_catalog.pg_class c
         where c.oid = history_oid;
        if relation_kind is distinct from 'r'
           or relation_persistence is distinct from 'p'
           or relation_is_partition then
            raise exception
                'normalized % receipt history relation is not a permanent ordinary table',
                table_spec.label;
        end if;

        select count(*)::integer
          into actual_column_count
          from pg_catalog.pg_attribute a
         where a.attrelid = history_oid
           and a.attnum > 0
           and not a.attisdropped;
        if actual_column_count <> expected_columns then
            raise exception
                'normalized % receipt history column shape is not canonical (expected %, found %)',
                table_spec.label, expected_columns, actual_column_count;
        end if;

        for column_spec in
            select *
              from (values
                  ('event_id'::text, 'int8'::regtype, true, 'event'::text),
                  ('receipt_id'::text, 'text'::regtype, true, 'none'::text),
                  ('event_sequence'::text, 'int8'::regtype, true, 'none'::text),
                  ('event_kind'::text, 'text'::regtype, true, 'initial'::text),
                  ('previous_receipt_hash'::text, 'text'::regtype, false, 'none'::text),
                  ('protocol_version'::text, 'text'::regtype, true, 'none'::text),
                  ('intent_id'::text, 'text'::regtype, true, 'none'::text),
                  ('term_id'::text, 'text'::regtype, true, 'none'::text),
                  ('backend_id'::text, 'text'::regtype, true, 'none'::text),
                  ('backend_kind'::text, 'text'::regtype, true, 'none'::text),
                  ('status'::text, 'text'::regtype, true, 'none'::text),
                  ('progression_class'::text, 'text'::regtype, true, 'none'::text),
                  ('settlement_reference'::text, 'text'::regtype, false, 'none'::text),
                  ('ledger_entry_id'::text, 'text'::regtype, false, 'none'::text),
                  ('reason'::text, 'text'::regtype, false, 'none'::text),
                  ('amount_credits'::text, 'int8'::regtype, false, 'none'::text),
                  ('finalized_at'::text, 'timestamptz'::regtype, true, 'none'::text),
                  ('receipt_json'::text, 'jsonb'::regtype, true, 'none'::text),
                  ('receipt_hash'::text, 'text'::regtype, true, 'none'::text),
                  ('created_at'::text, 'timestamptz'::regtype, true, 'now'::text)
              ) as expected(column_name, expected_type, expected_notnull, default_kind)
        loop
            select a.atttypid,
                   a.attnotnull,
                   a.attidentity::text,
                   a.attgenerated::text,
                   coalesce(pg_get_expr(ad.adbin, ad.adrelid), ''),
                   ad.oid
              into column_type, column_notnull, column_identity,
                   column_generated, column_default, column_default_oid
              from pg_catalog.pg_attribute a
              left join pg_catalog.pg_attrdef ad
                on ad.adrelid = a.attrelid
               and ad.adnum = a.attnum
             where a.attrelid = history_oid
               and a.attname = column_spec.column_name
               and not a.attisdropped;
            if not found then
                raise exception
                    'normalized % receipt history required column is missing: %',
                    table_spec.label, column_spec.column_name;
            end if;
            if column_type <> column_spec.expected_type then
                raise exception
                    'normalized % receipt history column % has incompatible type',
                    table_spec.label, column_spec.column_name;
            end if;
            if column_notnull is distinct from column_spec.expected_notnull then
                raise exception
                    'normalized % receipt history column % has incompatible nullability',
                    table_spec.label, column_spec.column_name;
            end if;
            if coalesce(column_generated, '') <> '' then
                raise exception
                    'normalized % receipt history column % must not be generated',
                    table_spec.label, column_spec.column_name;
            end if;

            normalized_default := regexp_replace(
                lower(coalesce(column_default, '')), '[[:space:]]+', '', 'g'
            );
            case column_spec.default_kind
                when 'event' then
                    -- Plain bigint/serial defaults remain supported for
                    -- interrupted deployments; the schema guard has already
                    -- proved ownership and sequence safety.
                    if column_identity not in ('', 'd') then
                        raise exception
                            'normalized % receipt history event_id identity mode is not generated-by-default',
                            table_spec.label;
                    end if;
                    if column_identity = ''
                       and (column_default_oid is null
                            or normalized_default !~ '^nextval\(.+\)$') then
                        raise exception
                            'normalized % receipt history event_id has no identity or sequence default',
                            table_spec.label;
                    end if;
                when 'initial' then
                    if column_identity <> '' then
                        raise exception
                            'normalized % receipt history event_kind must not be an identity column',
                            table_spec.label;
                    end if;
                    if column_default_oid is null then
                        execute format(
                            'alter table public.%I alter column event_kind set default ''initial''',
                            table_spec.history_table
                        );
                    elsif normalized_default !~ '^''initial''(::text)?$' then
                        raise exception
                            'normalized % receipt history event_kind default is not canonical',
                            table_spec.label;
                    end if;
                when 'now' then
                    if column_identity <> '' then
                        raise exception
                            'normalized % receipt history created_at must not be an identity column',
                            table_spec.label;
                    end if;
                    if column_default_oid is null then
                        execute format(
                            'alter table public.%I alter column created_at set default now()',
                            table_spec.history_table
                        );
                    elsif normalized_default !~ '^(now\(\)|current_timestamp)(::timestampwithtimezone)?$' then
                        raise exception
                            'normalized % receipt history created_at default is not canonical',
                            table_spec.label;
                    end if;
                when 'none' then
                    if column_identity <> '' or column_default_oid is not null then
                        raise exception
                            'normalized % receipt history column % has an unexpected generated/default expression',
                            table_spec.label, column_spec.column_name;
                    end if;
                else
                    raise exception
