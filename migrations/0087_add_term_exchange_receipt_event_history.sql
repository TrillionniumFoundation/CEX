begin;

-- Serialize concurrent receipt-schema migration runners.  The migrations are
-- transactional, but a plain partial history table can require
-- creation/adoption of a backing sequence; without one transaction-scoped
-- lock two runners could both observe the sequence as absent and race while
-- assigning ownership.  0085 and 0086 take this same lock so the whole
-- receipt-schema repair boundary is serialized.
select pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('cex:migration:term-exchange-receipt-schema', 0)
);

-- migration-check: allow-destructive
-- Reviewed rollback posture: this migration is expand-only.  The only
-- destructive-looking tokens are the append-only UPDATE/DELETE/TRUNCATE
-- guards; rollback never removes receipt evidence or disables those guards.

-- The 0026 projection tables intentionally retain one row per receipt_id for
-- compatibility with existing API/read models.  A retry can, however, move a
-- receipt from recoverable_hold to a final class without changing receipt_id.
-- These event tables preserve every distinct immutable snapshot in sequence;
-- the projection row is never used as a mutable history record.

create table if not exists public.league_term_exchange_receipt_events_v1 (
    event_id bigint generated by default as identity primary key,
    receipt_id text not null,
    event_sequence bigint not null,
    event_kind text not null default 'initial',
    previous_receipt_hash text,
    protocol_version text not null,
    intent_id text not null,
    term_id text not null,
    backend_id text not null,
    backend_kind text not null,
    status text not null,
    progression_class text not null,
    settlement_reference text,
    ledger_entry_id text,
    reason text,
    amount_credits bigint,
    finalized_at timestamptz not null,
    receipt_json jsonb not null,
    receipt_hash text not null,
    created_at timestamptz not null default now(),
    constraint league_term_exchange_receipt_events_sequence_v1
        check (event_sequence > 0),
    constraint league_term_exchange_receipt_events_previous_hash_v1
        check (previous_receipt_hash is null or previous_receipt_hash ~ '^sha256:[0-9a-f]{64}$'),
    constraint league_term_exchange_receipt_events_hash_v1
        check (receipt_hash ~ '^sha256:[0-9a-f]{64}$'),
    constraint league_term_exchange_receipt_events_status_v1
        check (length(btrim(status)) between 1 and 128),
    constraint league_term_exchange_receipt_events_progression_v1
        check (progression_class in (
            'progression_allowed', 'recoverable_hold', 'terminal_skip', 'hard_fail'
        )),
    constraint league_term_exchange_receipt_events_kind_v1
        check (event_kind in ('initial', 'backfill', 'hold', 'final', 'transition')),
    constraint league_term_exchange_receipt_events_amount_v1
        check (amount_credits is null or amount_credits >= 0),
    constraint league_term_exchange_receipt_events_json_v1
        check (jsonb_typeof(receipt_json) = 'object'),
    constraint league_term_exchange_receipt_events_identity_v1
        unique (receipt_id, event_sequence)
);

create table if not exists public.world_term_exchange_receipt_events_v1 (
    event_id bigint generated by default as identity primary key,
    receipt_id text not null,
    event_sequence bigint not null,
    event_kind text not null default 'initial',
    previous_receipt_hash text,
    protocol_version text not null,
    intent_id text not null,
    term_id text not null,
    backend_id text not null,
    backend_kind text not null,
    status text not null,
    progression_class text not null,
    settlement_reference text,
    ledger_entry_id text,
    reason text,
    amount_credits bigint,
    finalized_at timestamptz not null,
    receipt_json jsonb not null,
    receipt_hash text not null,
    created_at timestamptz not null default now(),
    constraint world_term_exchange_receipt_events_sequence_v1
        check (event_sequence > 0),
    constraint world_term_exchange_receipt_events_previous_hash_v1
        check (previous_receipt_hash is null or previous_receipt_hash ~ '^sha256:[0-9a-f]{64}$'),
    constraint world_term_exchange_receipt_events_hash_v1
        check (receipt_hash ~ '^sha256:[0-9a-f]{64}$'),
    constraint world_term_exchange_receipt_events_status_v1
        check (length(btrim(status)) between 1 and 128),
    constraint world_term_exchange_receipt_events_progression_v1
        check (progression_class in (
            'progression_allowed', 'recoverable_hold', 'terminal_skip', 'hard_fail'
        )),
    constraint world_term_exchange_receipt_events_kind_v1
        check (event_kind in ('initial', 'backfill', 'hold', 'final', 'transition')),
    constraint world_term_exchange_receipt_events_amount_v1
        check (amount_credits is null or amount_credits >= 0),
    constraint world_term_exchange_receipt_events_json_v1
        check (jsonb_typeof(receipt_json) = 'object'),
    constraint world_term_exchange_receipt_events_identity_v1
        unique (receipt_id, event_sequence)
);

-- `create table if not exists` does not retrofit the shape of a table that a
-- deployment runner committed before this migration completed.  In particular,
-- an empty partial table with a plain nullable `event_id` would let every later
-- insert carry NULL (and make the trigger's predecessor lookup ambiguous),
-- while a missing unique receipt projection would permit two authorities for
-- one receipt_id.  Repair only the mechanical, lossless pieces here; all
-- existing row semantics are checked by the guard below before any backfill.
do $history_schema_guard$
declare
    table_spec record;
    history_oid oid;
    projection_oid oid;
    relation_kind text;
    relation_persistence text;
    relation_is_partition boolean;
    event_attnum smallint;
    event_type oid;
    event_identity text;
    event_default_exists boolean;
    event_default text;
    event_default_oid oid;
    max_event_id bigint;
    sequence_name text;
    sequence_qualified text;
    sequence_oid oid;
    sequence_type oid;
    sequence_increment bigint;
    sequence_max bigint;
    sequence_min bigint;
    sequence_cycle boolean;
    sequence_last bigint;
    sequence_called boolean;
    history_receipt_attnum smallint;
    history_sequence_attnum smallint;
    history_intent_attnum smallint;
    history_receipt_type oid;
    history_sequence_type oid;
    history_intent_type oid;
    projection_receipt_attnum smallint;
    projection_receipt_type oid;
    projection_receipt_notnull boolean;
    has_projection_unique boolean;
    has_projection_null boolean;
    has_projection_duplicate boolean;
    projection_index_name text;
    projection_index_relation oid;
    projection_index_is_canonical boolean;
    projection_key_opclasses oid[];
    projection_key_collations oid[];
begin
    for table_spec in
        select *
          from (values
              ('league_term_exchange_receipt_events_v1'::text, 'league_term_exchange_receipts'::text, 'league'::text),
              ('world_term_exchange_receipt_events_v1'::text, 'world_term_exchange_receipts'::text, 'world'::text)
          ) as allowed_tables(history_table, projection_table, label)
    loop
        history_oid := to_regclass('public.' || table_spec.history_table);
        if history_oid is null then
            raise exception
                'normalized % receipt history table is missing', table_spec.label;
        end if;
        select c.relkind::text, c.relpersistence::text, c.relispartition
          into relation_kind, relation_persistence, relation_is_partition
          from pg_catalog.pg_class c
         where c.oid = history_oid;
        if relation_kind is distinct from 'r'
           or relation_persistence is distinct from 'p'
           or relation_is_partition then
            raise exception
                'normalized % receipt history relation is not a permanent ordinary table',
                table_spec.label;
        end if;

        -- Locate event_id through the catalog first so a partial table that
        -- omitted the column can be completed without guessing at row values.
        select a.attnum,
               a.atttypid,
               a.attidentity::text,
               (ad.oid is not null),
               coalesce(pg_get_expr(ad.adbin, ad.adrelid), ''),
               ad.oid
          into event_attnum, event_type, event_identity,
               event_default_exists, event_default, event_default_oid
          from pg_catalog.pg_attribute a
          left join pg_catalog.pg_attrdef ad
            on ad.adrelid = a.attrelid
           and ad.adnum = a.attnum
         where a.attrelid = history_oid
           and a.attname = 'event_id'
           and not a.attisdropped;

        if event_attnum is null then
            execute format(
                'alter table public.%I add column event_id bigint generated by default as identity',
                table_spec.history_table
            );
            select a.attnum,
                   a.atttypid,
                   a.attidentity::text,
                   (ad.oid is not null),
                   coalesce(pg_get_expr(ad.adbin, ad.adrelid), ''),
                   ad.oid
              into event_attnum, event_type, event_identity,
                   event_default_exists, event_default, event_default_oid
              from pg_catalog.pg_attribute a
              left join pg_catalog.pg_attrdef ad
                on ad.adrelid = a.attrelid
               and ad.adnum = a.attnum
             where a.attrelid = history_oid
               and a.attname = 'event_id'
               and not a.attisdropped;
        end if;
        if event_type <> 'int8'::regtype then
            raise exception
                'normalized % receipt history event_id must be bigint', table_spec.label;
        end if;

        -- Locate the other identity columns before the pre-existing-row
        -- validator issues its wide SELECT.  We do not guess or add these
        -- columns: a partially-created authority with a missing key column
        -- must fail closed with a controlled migration error.
        select max(a.attnum) filter (where a.attname = 'receipt_id'),
               max(a.attnum) filter (where a.attname = 'event_sequence'),
               max(a.attnum) filter (where a.attname = 'intent_id'),
               max(a.atttypid) filter (where a.attname = 'receipt_id'),
               max(a.atttypid) filter (where a.attname = 'event_sequence'),
               max(a.atttypid) filter (where a.attname = 'intent_id')
          into history_receipt_attnum, history_sequence_attnum,
               history_intent_attnum, history_receipt_type,
               history_sequence_type, history_intent_type
          from pg_catalog.pg_attribute a
         where a.attrelid = history_oid
           and not a.attisdropped
           and a.attname in ('receipt_id', 'event_sequence', 'intent_id');
        if history_receipt_attnum is null
           or history_sequence_attnum is null
           or history_intent_attnum is null then
            raise exception
                'normalized % receipt history is missing an identity column', table_spec.label;
        end if;
        if history_receipt_type <> 'text'::regtype
           or history_sequence_type <> 'int8'::regtype
           or history_intent_type <> 'text'::regtype then
            raise exception
                'normalized % receipt history identity columns have incompatible types',
                table_spec.label;
        end if;

        -- A plain bigint column is made append-safe with a private sequence.
        -- Existing positive ids are preserved and the sequence is advanced
        -- beyond their maximum; malformed NULL/negative rows are rejected by
        -- the pre-existing-row validator below rather than silently repaired.
        if coalesce(event_identity, '') = '' and not event_default_exists then
            sequence_name := table_spec.history_table || '_event_id_seq';
            sequence_qualified := 'public.' || sequence_name;
            -- CREATE SEQUENCE IF NOT EXISTS compares only the relation name;
            -- retaining a table/view with that name would make the new default
            -- unsafe.  Accept an existing sequence, but reject every other
            -- relation kind explicitly.
            select c.oid
              into sequence_oid
              from pg_catalog.pg_class c
              join pg_catalog.pg_namespace n on n.oid = c.relnamespace
             where n.nspname = 'public'
               and c.relname = sequence_name;
            if sequence_oid is not null then
                if not exists (
                    select 1
                      from pg_catalog.pg_class c
                     where c.oid = sequence_oid
                       and c.relkind = 'S'
                       and c.relpersistence = 'p'
                ) then
                    raise exception
                        'normalized % receipt history event_id sequence is not a permanent sequence',
                        table_spec.label;
                end if;
            else
                -- Keep the existence check race-safe.  Two deployment
                -- runners can observe the name as absent before either DDL
                -- commits; IF NOT EXISTS lets the second runner wait for the
                -- first and then re-use the same sequence.  We still inspect
                -- the resulting relation below and fail closed if another
                -- object (table/view/index) occupies the expected name.
                execute format('create sequence if not exists public.%I', sequence_name);
                select c.oid
                  into sequence_oid
                  from pg_catalog.pg_class c
                  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
                 where n.nspname = 'public'
                   and c.relname = sequence_name;
                if sequence_oid is null then
                    raise exception
                        'normalized % receipt history event_id sequence could not be created',
                        table_spec.label;
                end if;
            end if;
            if not exists (
                select 1
                  from pg_catalog.pg_class c
                 where c.oid = sequence_oid
                   and c.relkind = 'S'
                   and c.relpersistence = 'p'
            ) then
                raise exception
                    'normalized % receipt history event_id sequence is not a permanent sequence',
                    table_spec.label;
            end if;
            -- Never steal a sequence that is owned by, or referenced by the
            -- default of, another column.  The final dependency check below
            -- runs after `ALTER SEQUENCE ... OWNED BY`; this pre-check is what
            -- preserves the original ownership boundary for an existing
            -- partial deployment.
            if (
                exists (
                    select 1
                      from pg_catalog.pg_depend d
                     where d.classid = 'pg_catalog.pg_class'::regclass
                       and d.objid = sequence_oid
                       and d.deptype in ('a', 'i')
                       and not (
                           d.refclassid = 'pg_catalog.pg_class'::regclass
                           and d.refobjid = history_oid
                           and d.refobjsubid = event_attnum
                       )
                )
                or exists (
                    select 1
                      from pg_catalog.pg_depend d
                     where d.classid = 'pg_catalog.pg_attrdef'::regclass
                       and d.refclassid = 'pg_catalog.pg_class'::regclass
                       and d.refobjid = sequence_oid
                       -- On the no-default branch event_default_oid is NULL.
                       -- `d.objid = NULL` would make the old NOT(...) predicate
                       -- UNKNOWN and hide a dependency from another column's
                       -- default, allowing this migration to steal a shared
                       -- sequence.  Make the NULL case explicit so every
                       -- referencing attrdef is treated as an ownership
                       -- conflict unless it is this column's own default.
                       and (
                           event_default_oid is null
                           or d.objid <> event_default_oid
                       )
                )
            ) then
                raise exception
                    'normalized % receipt history event_id sequence is already used by another column/default',
                    table_spec.label;
            end if;
            -- `setval` is intentionally non-transactional in PostgreSQL.  Do
            -- every sequence-safety check before changing its state so a
            -- failed upgrade cannot leave an exhausted/advanced generator
            -- behind after the DDL transaction rolls back.  The same checks
            -- are repeated below after the default/ownership repair for
            -- identity and serial-style paths.
            select s.seqtypid, s.seqincrement, s.seqmax, s.seqmin, s.seqcycle
              into sequence_type, sequence_increment, sequence_max,
                   sequence_min, sequence_cycle
              from pg_catalog.pg_sequence s
             where s.seqrelid = sequence_oid;
            if not found
               or sequence_type <> 'int8'::regtype
               or sequence_increment <= 0
               or sequence_min < 1
               or sequence_cycle then
                raise exception
                    'normalized % receipt history event_id sequence is unsafe', table_spec.label;
            end if;
            execute format(
                'select last_value::bigint, is_called from %s',
                sequence_qualified
            ) into sequence_last, sequence_called;
            -- An uncalled sequence returns its stored last_value on the next
            -- call, so MAXVALUE itself is still one valid candidate.  Once
            -- called, MAXVALUE (or any value without one full increment of
            -- headroom) is exhausted.
            if sequence_last is null
               or sequence_last < sequence_min
               or sequence_last > sequence_max
               or (sequence_last = sequence_max and sequence_called)
               or (sequence_called and sequence_last > sequence_max - sequence_increment) then
                raise exception
                    'normalized % receipt history event_id sequence is exhausted', table_spec.label;
            end if;
            execute format(
                'select coalesce(max(event_id), 0) from public.%I',
                table_spec.history_table
            ) into max_event_id;
            if max_event_id >= sequence_max
               or max_event_id > sequence_max - sequence_increment then
                raise exception
                    'normalized % receipt history event_id sequence is exhausted', table_spec.label;
            end if;
            if max_event_id > 0 then
                -- `setval` is non-transactional.  Use transactional RESTART
                -- and advance by one increment so the first generated id is
                -- strictly above any manually supplied event_id.
                execute format(
                    'alter sequence %s restart with %s',
                    sequence_qualified,
                    max_event_id + sequence_increment
                );
            else
                execute format(
                    'alter sequence %s restart with %s',
                    sequence_qualified,
                    sequence_min
                );
            end if;
            execute format(
                'alter table public.%I alter column event_id set default nextval(%L::regclass)',
                table_spec.history_table, sequence_qualified
            );
            execute format(
                'alter sequence public.%I owned by public.%I.event_id',
                sequence_name, table_spec.history_table
            );
        elsif coalesce(event_identity, '') = '' then
            -- A plain bigint default is accepted only when it is the canonical
            -- standalone nextval expression.  Merely finding the substring
            -- `nextval(` would also accept arithmetic/coalesce wrappers that
            -- can emit duplicates or NULLs.
            if regexp_replace(lower(coalesce(event_default, '')), '[[:space:]]+', '', 'g')
                   !~ '^nextval\(.+\)$' then
                raise exception
                    'normalized % receipt history event_id has an unsafe default', table_spec.label;
            end if;
        end if;

        -- Identity and serial-style defaults can still point at a sequence
        -- whose state lags manually supplied rows.  Resolve the owned backing
        -- sequence and validate its monotonic, non-cycling bigint shape before
        -- advancing it beyond the current maximum.  An unowned/custom
        -- nextval is ambiguous and therefore fails closed.
        sequence_qualified := pg_get_serial_sequence(
            format('public.%I', table_spec.history_table),
            'event_id'
        );
        if sequence_qualified is null then
            raise exception
                'normalized % receipt history event_id default/identity has no owned sequence',
                table_spec.label;
        end if;
        sequence_oid := to_regclass(sequence_qualified);
        if sequence_oid is null then
            raise exception
                'normalized % receipt history event_id default/identity sequence is missing',
                table_spec.label;
        end if;
        if not exists (
            select 1
              from pg_catalog.pg_class c
             where c.oid = sequence_oid
               and c.relkind = 'S'
               and c.relpersistence = 'p'
        ) then
            raise exception
                'normalized % receipt history event_id sequence is not a permanent sequence',
                table_spec.label;
        end if;
        select s.seqtypid, s.seqincrement, s.seqmax, s.seqmin, s.seqcycle
          into sequence_type, sequence_increment, sequence_max,
               sequence_min, sequence_cycle
          from pg_catalog.pg_sequence s
         where s.seqrelid = sequence_oid;
        if not found
           or sequence_type <> 'int8'::regtype
           or sequence_increment <= 0
           or sequence_min < 1
           or sequence_cycle then
            raise exception
                'normalized % receipt history event_id sequence is unsafe', table_spec.label;
        end if;
        if exists (
               select 1
                 from pg_catalog.pg_depend d
                where d.classid = 'pg_catalog.pg_class'::regclass
                  and d.objid = sequence_oid
                  and d.deptype in ('a', 'i')
                  and not (
                      d.refclassid = 'pg_catalog.pg_class'::regclass
                      and d.refobjid = history_oid
                      and d.refobjsubid = event_attnum
                  )
           ) then
            raise exception
                'normalized % receipt history event_id sequence is owned by another column',
                table_spec.label;
        end if;
        if event_identity = ''
           and event_default_oid is not null
           and not exists (
               select 1
                 from pg_catalog.pg_depend d
                where d.classid = 'pg_catalog.pg_attrdef'::regclass
                  and d.objid = event_default_oid
                  and d.refclassid = 'pg_catalog.pg_class'::regclass
                  and d.refobjid = sequence_oid
           ) then
            raise exception
                'normalized % receipt history event_id default does not use its owned sequence',
                table_spec.label;
        end if;
        -- A plain `nextval(...)` default is not sufficient by itself.  Require
        -- the resolved sequence to be owned by this exact event_id column so a
        -- later DROP/ALTER of an unrelated table cannot silently invalidate
        -- the append key, and so a hand-authored unowned sequence cannot be
        -- adopted as authority without an explicit ownership decision.  The
        -- canonical identity sequence uses dependency type `i`; serial/plain
        -- defaults use `a`.
        if not exists (
            select 1
              from pg_catalog.pg_depend d
             where d.classid = 'pg_catalog.pg_class'::regclass
               and d.objid = sequence_oid
               and d.refclassid = 'pg_catalog.pg_class'::regclass
               and d.refobjid = history_oid
               and d.refobjsubid = event_attnum
               and d.deptype in ('a', 'i')
        ) then
            raise exception
                'normalized % receipt history event_id sequence is not owned by event_id',
                table_spec.label;
        end if;
        -- A sequence can be owned by this event_id column while another
        -- column still references it through a normal DEFAULT nextval().
        -- Keep the append generator private; exclude only this column's own
        -- pg_attrdef (identity columns have no attribute default).
        if exists (
            select 1
              from pg_catalog.pg_depend d
              join pg_catalog.pg_attrdef ad on ad.oid = d.objid
             where d.classid = 'pg_catalog.pg_attrdef'::regclass
               and d.refclassid = 'pg_catalog.pg_class'::regclass
               and d.refobjid = sequence_oid
               and not (ad.adrelid = history_oid and ad.adnum = event_attnum)
        ) then
            raise exception
                'normalized % receipt history event_id sequence is already used by another column/default',
                table_spec.label;
        end if;
        execute format(
            'select coalesce(max(event_id), 0) from public.%I',
            table_spec.history_table
        ) into max_event_id;
        if max_event_id >= sequence_max then
            raise exception
                'normalized % receipt history event_id sequence is exhausted', table_spec.label;
        end if;
        -- `nextval` advances by the sequence increment after a called
        -- sequence value.  A sequence whose current maximum is only one
        -- increment below MAXVALUE is consequently already exhausted for the
        -- append path, even though the current value is still below MAXVALUE.
        -- Both operands are positive/valid bigint sequence metadata, so this
        -- subtraction is overflow-safe.
        if max_event_id > sequence_max - sequence_increment then
            raise exception
                'normalized % receipt history event_id sequence is exhausted', table_spec.label;
        end if;
        execute format(
            'select last_value::bigint, is_called from %s',
            sequence_qualified
        ) into sequence_last, sequence_called;
        -- An uncalled sequence returns its stored last_value on the next
        -- call, so MAXVALUE itself is still one valid candidate.  Once
        -- called, MAXVALUE (or any value without one full increment of
        -- headroom) is exhausted.
        if sequence_last is null
           or sequence_last < sequence_min
           or sequence_last > sequence_max
           or (sequence_last = sequence_max and sequence_called) then
            raise exception
                'normalized % receipt history event_id sequence is exhausted', table_spec.label;
        end if;
        if sequence_called
           and sequence_last > sequence_max - sequence_increment then
            raise exception
                'normalized % receipt history event_id sequence is exhausted', table_spec.label;
        end if;
        if sequence_last is null
           or sequence_last < max_event_id
           or (sequence_last = max_event_id and not sequence_called) then
            execute format(
                'alter sequence %s restart with %s',
                sequence_qualified,
                max_event_id + sequence_increment
            );
        end if;

        projection_oid := to_regclass('public.' || table_spec.projection_table);
        if projection_oid is null then
            raise exception
                'normalized % receipt projection table is missing', table_spec.label;
        end if;
        select c.relkind::text, c.relpersistence::text, c.relispartition
          into relation_kind, relation_persistence, relation_is_partition
          from pg_catalog.pg_class c
         where c.oid = projection_oid;
        if relation_kind is distinct from 'r'
           or relation_persistence is distinct from 'p'
           or relation_is_partition then
            raise exception
                'normalized % receipt projection relation is not a permanent ordinary table',
                table_spec.label;
        end if;
        select a.attnum, a.atttypid, a.attnotnull
          into projection_receipt_attnum, projection_receipt_type,
               projection_receipt_notnull
          from pg_catalog.pg_attribute a
         where a.attrelid = projection_oid
           and a.attname = 'receipt_id'
           and not a.attisdropped;
        if projection_receipt_attnum is null
           or projection_receipt_type <> 'text'::regtype then
            raise exception
                'normalized % receipt projection receipt_id must be text', table_spec.label;
        end if;
        execute format(
            'select exists (select 1 from public.%I where receipt_id is null)',
            table_spec.projection_table
        ) into has_projection_null;
        if has_projection_null then
            raise exception
                'normalized % receipt projection contains a NULL receipt_id', table_spec.label;
        end if;
        execute format(
            'select exists (
                 select 1 from public.%I group by receipt_id having count(*) > 1
             )',
            table_spec.projection_table
        ) into has_projection_duplicate;
        if has_projection_duplicate then
            raise exception
                'normalized % receipt projection contains duplicate receipt_ids', table_spec.label;
        end if;
        if not projection_receipt_notnull then
            execute format(
                'alter table public.%I alter column receipt_id set not null',
                table_spec.projection_table
            );
        end if;

        -- Match the default btree operator class and the column's declared
        -- collation as well as the key attribute.  An otherwise valid-looking
        -- text_pattern_ops or explicitly-C-collated index is not the canonical
        -- receipt identity index and must not be adopted as authority.
        select array_agg(opc.oid order by key_part.ordinality),
               array_agg(a.attcollation order by key_part.ordinality)
          into projection_key_opclasses, projection_key_collations
          from unnest(array[projection_receipt_attnum]::smallint[]) with ordinality
               as key_part(attnum, ordinality)
          join pg_catalog.pg_attribute a
            on a.attrelid = projection_oid
           and a.attnum = key_part.attnum
           and not a.attisdropped
          join pg_catalog.pg_opclass opc
            on opc.opcintype = a.atttypid
           and opc.opcdefault
           and opc.opcnamespace = 'pg_catalog'::regnamespace
          join pg_catalog.pg_am am
            on am.oid = opc.opcmethod
           and am.amname = 'btree';
        if projection_key_opclasses is null or projection_key_collations is null then
            raise exception
                'normalized % receipt projection identity key operator class/collation is unavailable',
                table_spec.label;
        end if;

        -- A primary key/unique constraint from 0026 satisfies this check.  A
        -- partially-created table may instead have only a non-constraint
        -- unique index, which is also valid authority as long as it is global
        -- (not partial) and covers receipt_id alone.
        select exists (
            select 1
             from pg_catalog.pg_class index_class
             join pg_catalog.pg_index i on i.indexrelid = index_class.oid
             join pg_catalog.pg_am am on am.oid = index_class.relam
             where index_class.relkind = 'i'
               and index_class.relpersistence = 'p'
               and not index_class.relispartition
               and index_class.relowner = (
                   select target.relowner
                     from pg_catalog.pg_class target
                    where target.oid = projection_oid
               )
               and am.amname = 'btree'
               and i.indrelid = projection_oid
               and i.indisunique
               and i.indisvalid
               and i.indisready
               and i.indislive
               and i.indimmediate
               and i.indpred is null
               and i.indexprs is null
               and i.indnkeyatts = 1
               and i.indnatts = 1
               and i.indkey[0] = projection_receipt_attnum
               and (
                   select array_agg(key_part.opclass_oid order by key_part.ordinality)
                     from unnest(i.indclass::oid[]) with ordinality
                          as key_part(opclass_oid, ordinality)
               ) = projection_key_opclasses
               and (
                   select array_agg(key_part.collation_oid order by key_part.ordinality)
                     from unnest(i.indcollation::oid[]) with ordinality
                          as key_part(collation_oid, ordinality)
               ) = projection_key_collations
        ) into has_projection_unique;
        -- Inspect the canonical fallback name even when another valid unique
        -- index already proves the functional invariant.  Otherwise a table,
        -- view, or wrong-table index occupying this schema-scoped name would be
        -- skipped by the `if not has_projection_unique` branch.
        projection_index_name := 'uq_' || table_spec.projection_table || '_receipt_id_v1';
        select c.oid
          into projection_index_relation
          from pg_catalog.pg_class c
          join pg_catalog.pg_namespace n on n.oid = c.relnamespace
         where n.nspname = 'public'
           and c.relname = projection_index_name;
        if projection_index_relation is not null then
            select exists (
                select 1
                  from pg_catalog.pg_class index_class
                  join pg_catalog.pg_index i on i.indexrelid = index_class.oid
                  join pg_catalog.pg_am am on am.oid = index_class.relam
                 where index_class.oid = projection_index_relation
                   and index_class.relkind = 'i'
                   and index_class.relpersistence = 'p'
                   and not index_class.relispartition
                   and index_class.relowner = (
                       select target.relowner
                         from pg_catalog.pg_class target
                        where target.oid = projection_oid
                   )
                   and am.amname = 'btree'
                   and i.indrelid = projection_oid
                   and i.indisunique
                   and i.indisvalid
                   and i.indisready
                   and i.indislive
                   and i.indimmediate
                   and i.indpred is null
                   and i.indexprs is null
                   and i.indnkeyatts = 1
                   and i.indnatts = 1
                   and i.indkey[0] = projection_receipt_attnum
                   and (
                       select array_agg(key_part.opclass_oid order by key_part.ordinality)
                         from unnest(i.indclass::oid[]) with ordinality
                              as key_part(opclass_oid, ordinality)
                   ) = projection_key_opclasses
                   and (
                       select array_agg(key_part.collation_oid order by key_part.ordinality)
                         from unnest(i.indcollation::oid[]) with ordinality
                              as key_part(collation_oid, ordinality)
                   ) = projection_key_collations
            ) into projection_index_is_canonical;
            if projection_index_is_canonical is distinct from true then
                -- CREATE INDEX IF NOT EXISTS only compares the relation name;
                -- it would silently retain an invalid or differently-shaped
                -- object and leave receipt identity non-unique.
                raise exception
                    'normalized % receipt projection has an incompatible receipt_id key',
                    table_spec.label;
            end if;
        elsif not has_projection_unique then
            execute format(
                'create unique index %I on public.%I (receipt_id)',
                projection_index_name,
                table_spec.projection_table
            );
        end if;
    end loop;
end
$history_schema_guard$;

-- Preflight the typed catalog before any wide `record`-based row validator is
-- planned.  PostgreSQL caches a PL/pgSQL record-field expression's composite
-- type; if one lane has (for example) `timestamp` while the other has
-- `timestamptz`, the later validator can otherwise fail with an internal
-- cached-plan type error instead of the migration's controlled schema error.
-- This pass deliberately defers nullability until after the row audit (the
-- partial-upgrade path may still contain NULLs), but it checks every column's
-- exact type/generated/default shape and repairs only omitted runtime defaults.
do $history_catalog_type_preflight$
declare
    table_spec record;
    history_oid oid;
    relation_kind text;
    relation_persistence text;
    relation_is_partition boolean;
    actual_column_count integer;
    column_spec record;
    column_type oid;
    column_identity text;
    column_generated text;
    column_default text;
    column_default_oid oid;
    normalized_default text;
    expected_columns constant integer := 20;
begin
    for table_spec in
        select *
          from (values
              ('league_term_exchange_receipt_events_v1'::text, 'league'::text),
              ('world_term_exchange_receipt_events_v1'::text, 'world'::text)
          ) as allowed_tables(history_table, label)
    loop
        history_oid := to_regclass('public.' || table_spec.history_table);
        select c.relkind::text, c.relpersistence::text, c.relispartition
          into relation_kind, relation_persistence, relation_is_partition
          from pg_catalog.pg_class c
         where c.oid = history_oid;
        if relation_kind is distinct from 'r'
           or relation_persistence is distinct from 'p'
           or relation_is_partition then
            raise exception
                'normalized % receipt history relation is not a permanent ordinary table',
                table_spec.label;
        end if;
        select count(*)::integer
          into actual_column_count
          from pg_catalog.pg_attribute a
         where a.attrelid = history_oid
           and a.attnum > 0
           and not a.attisdropped;
        if actual_column_count <> expected_columns then
            raise exception
                'normalized % receipt history column shape is not canonical (expected %, found %)',
                table_spec.label, expected_columns, actual_column_count;
        end if;

        for column_spec in
            select *
              from (values
                  ('event_id'::text, 'int8'::regtype, 'event'::text),
                  ('receipt_id'::text, 'text'::regtype, 'none'::text),
                  ('event_sequence'::text, 'int8'::regtype, 'none'::text),
                  ('event_kind'::text, 'text'::regtype, 'initial'::text),
                  ('previous_receipt_hash'::text, 'text'::regtype, 'none'::text),
                  ('protocol_version'::text, 'text'::regtype, 'none'::text),
                  ('intent_id'::text, 'text'::regtype, 'none'::text),
                  ('term_id'::text, 'text'::regtype, 'none'::text),
                  ('backend_id'::text, 'text'::regtype, 'none'::text),
                  ('backend_kind'::text, 'text'::regtype, 'none'::text),
                  ('status'::text, 'text'::regtype, 'none'::text),
                  ('progression_class'::text, 'text'::regtype, 'none'::text),
                  ('settlement_reference'::text, 'text'::regtype, 'none'::text),
                  ('ledger_entry_id'::text, 'text'::regtype, 'none'::text),
                  ('reason'::text, 'text'::regtype, 'none'::text),
                  ('amount_credits'::text, 'int8'::regtype, 'none'::text),
                  ('finalized_at'::text, 'timestamptz'::regtype, 'none'::text),
                  ('receipt_json'::text, 'jsonb'::regtype, 'none'::text),
                  ('receipt_hash'::text, 'text'::regtype, 'none'::text),
                  ('created_at'::text, 'timestamptz'::regtype, 'now'::text)
              ) as expected(column_name, expected_type, default_kind)
        loop
            select a.atttypid,
                   a.attidentity::text,
                   a.attgenerated::text,
                   coalesce(pg_get_expr(ad.adbin, ad.adrelid), ''),
                   ad.oid
              into column_type, column_identity, column_generated,
                   column_default, column_default_oid
              from pg_catalog.pg_attribute a
              left join pg_catalog.pg_attrdef ad
                on ad.adrelid = a.attrelid
               and ad.adnum = a.attnum
             where a.attrelid = history_oid
               and a.attname = column_spec.column_name
               and not a.attisdropped;
            if not found then
                raise exception
                    'normalized % receipt history required column is missing: %',
                    table_spec.label, column_spec.column_name;
            end if;
            if column_type <> column_spec.expected_type then
                raise exception
                    'normalized % receipt history column % has incompatible type',
                    table_spec.label, column_spec.column_name;
            end if;
            if coalesce(column_generated, '') <> '' then
                raise exception
                    'normalized % receipt history column % must not be generated',
                    table_spec.label, column_spec.column_name;
            end if;
            normalized_default := regexp_replace(
                lower(coalesce(column_default, '')), '[[:space:]]+', '', 'g'
            );
            case column_spec.default_kind
                when 'event' then
                    if column_identity not in ('', 'd') then
                        raise exception
                            'normalized % receipt history event_id identity mode is not generated-by-default',
                            table_spec.label;
                    end if;
                    if column_identity = ''
                       and (column_default_oid is null
                            or normalized_default !~ '^nextval\(.+\)$') then
                        raise exception
                            'normalized % receipt history event_id has no identity or sequence default',
                            table_spec.label;
                    end if;
                when 'initial' then
                    if column_identity <> '' then
                        raise exception
                            'normalized % receipt history event_kind must not be an identity column',
                            table_spec.label;
                    end if;
                    if column_default_oid is null then
                        execute format(
                            'alter table public.%I alter column event_kind set default ''initial''',
                            table_spec.history_table
                        );
                    elsif normalized_default !~ '^''initial''(::text)?$' then
                        raise exception
                            'normalized % receipt history event_kind default is not canonical',
                            table_spec.label;
                    end if;
                when 'now' then
                    if column_identity <> '' then
                        raise exception
                            'normalized % receipt history created_at must not be an identity column',
                            table_spec.label;
                    end if;
                    if column_default_oid is null then
                        execute format(
                            'alter table public.%I alter column created_at set default now()',
                            table_spec.history_table
                        );
                    elsif normalized_default !~ '^(now\(\)|current_timestamp)(::timestampwithtimezone)?$' then
                        raise exception
                            'normalized % receipt history created_at default is not canonical',
                            table_spec.label;
                    end if;
                when 'none' then
                    if column_identity <> '' or column_default_oid is not null then
                        raise exception
                            'normalized % receipt history column % has an unexpected generated/default expression',
                            table_spec.label, column_spec.column_name;
                    end if;
                else
                    raise exception
                        'normalized % receipt history catalog preflight has an unknown default kind',
                        table_spec.label;
            end case;
        end loop;
    end loop;
end
$history_catalog_type_preflight$;

-- Performance indexes are not authority by themselves, but their canonical
-- names are part of the published schema.  `CREATE INDEX IF NOT EXISTS` only
-- compares a schema-scoped relation name; a same-named index on another table,
-- a non-index relation, or an invalid/wrongly-ordered index would otherwise
-- produce a silent success while leaving the history catalog incomplete.
do $history_performance_index_guard$
declare
    index_spec record;
    history_oid oid;
    index_oid oid;
    index_is_canonical boolean;
    expected_attnums smallint[];
    expected_opclasses oid[];
    expected_collations oid[];
    expected_column_count integer;
    matched_column_count integer;
begin
    for index_spec in
        select *
          from (values
              (
                  'league_term_exchange_receipt_events_v1'::text,
                  'league'::text,
                  'idx_league_term_exchange_receipt_events_latest_v1'::text,
                  array['receipt_id', 'event_sequence', 'event_id']::text[],
                  array[0, 3, 3]::smallint[],
                  'receipt_id, event_sequence desc, event_id desc'::text
              ),
              (
                  'league_term_exchange_receipt_events_v1'::text,
                  'league'::text,
                  'idx_league_term_exchange_receipt_events_finalized_v1'::text,
                  array['finalized_at', 'event_id']::text[],
                  array[3, 3]::smallint[],
                  'finalized_at desc, event_id desc'::text
              ),
              (
                  'league_term_exchange_receipt_events_v1'::text,
                  'league'::text,
                  'idx_league_term_exchange_receipt_events_intent_v1'::text,
                  array['intent_id', 'finalized_at', 'event_id']::text[],
                  array[0, 3, 3]::smallint[],
                  'intent_id, finalized_at desc, event_id desc'::text
              ),
              (
                  'world_term_exchange_receipt_events_v1'::text,
                  'world'::text,
                  'idx_world_term_exchange_receipt_events_latest_v1'::text,
                  array['receipt_id', 'event_sequence', 'event_id']::text[],
                  array[0, 3, 3]::smallint[],
                  'receipt_id, event_sequence desc, event_id desc'::text
              ),
              (
                  'world_term_exchange_receipt_events_v1'::text,
                  'world'::text,
                  'idx_world_term_exchange_receipt_events_finalized_v1'::text,
                  array['finalized_at', 'event_id']::text[],
                  array[3, 3]::smallint[],
                  'finalized_at desc, event_id desc'::text
              ),
              (
                  'world_term_exchange_receipt_events_v1'::text,
                  'world'::text,
                  'idx_world_term_exchange_receipt_events_intent_v1'::text,
                  array['intent_id', 'finalized_at', 'event_id']::text[],
                  array[0, 3, 3]::smallint[],
                  'intent_id, finalized_at desc, event_id desc'::text
              )
          ) as allowed_indexes(
              history_table, label, index_name, index_columns, index_options, index_sql
          )
    loop
        history_oid := to_regclass('public.' || index_spec.history_table);
        if history_oid is null then
            raise exception
                'normalized % receipt history table is missing for performance index',
                index_spec.label;
        end if;

        expected_column_count := cardinality(index_spec.index_columns);
        select array_agg(a.attnum order by column_spec.ordinality)::smallint[],
               array_agg(opc.oid order by column_spec.ordinality)::oid[],
               array_agg(a.attcollation order by column_spec.ordinality)::oid[],
               count(a.attnum)::integer
          into expected_attnums, expected_opclasses, expected_collations,
               matched_column_count
          from unnest(index_spec.index_columns) with ordinality as column_spec(column_name, ordinality)
          left join pg_catalog.pg_attribute a
            on a.attrelid = history_oid
           and a.attname = column_spec.column_name
           and not a.attisdropped
          join pg_catalog.pg_opclass opc
            on opc.opcintype = a.atttypid
           and opc.opcdefault
           and opc.opcnamespace = 'pg_catalog'::regnamespace
          join pg_catalog.pg_am am_expected
            on am_expected.oid = opc.opcmethod
           and am_expected.amname = 'btree';
        if matched_column_count <> expected_column_count then
            raise exception
                'normalized % receipt history is missing a performance-index column',
                index_spec.label;
        end if;
        if expected_opclasses is null or expected_collations is null then
            raise exception
                'normalized % receipt history performance-index operator class/collation is unavailable',
                index_spec.label;
        end if;

        -- Look up any relation kind.  A table/view/sequence with the canonical
        -- name must be a hard conflict rather than an object to ignore.
        select c.oid
          into index_oid
          from pg_catalog.pg_class c
          join pg_catalog.pg_namespace n on n.oid = c.relnamespace
         where n.nspname = 'public'
           and c.relname = index_spec.index_name;
        if index_oid is not null then
            select exists (
                select 1
                  from pg_catalog.pg_class c
                  join pg_catalog.pg_index i on i.indexrelid = c.oid
                  join pg_catalog.pg_am am on am.oid = c.relam
                 where c.oid = index_oid
                   and c.relkind = 'i'
                   and c.relpersistence = 'p'
                   and not c.relispartition
                   and c.relowner = (
                       select target.relowner
                         from pg_catalog.pg_class target
                        where target.oid = history_oid
                   )
                   and am.amname = 'btree'
                   and i.indrelid = history_oid
                   and not i.indisunique
                   and not i.indisprimary
                   and not i.indisexclusion
                   and i.indisvalid
                   and i.indisready
                   and i.indislive
                   and i.indimmediate
                   and i.indpred is null
                   and i.indexprs is null
                   and i.indnkeyatts = expected_column_count
                   and i.indnatts = expected_column_count
                   and (
                       select array_agg(key_part.attnum::smallint order by key_part.ordinality)
                         from unnest(i.indkey) with ordinality as key_part(attnum, ordinality)
                   ) = expected_attnums
                   and (
                       select array_agg(option_part.option_value::smallint order by option_part.ordinality)
                         from unnest(i.indoption) with ordinality as option_part(option_value, ordinality)
                   ) = index_spec.index_options
                   and (
                       select array_agg(opclass_part.opclass_oid order by opclass_part.ordinality)
                         from unnest(i.indclass::oid[]) with ordinality
                              as opclass_part(opclass_oid, ordinality)
                   ) = expected_opclasses
                   and (
                       select array_agg(collation_part.collation_oid order by collation_part.ordinality)
                         from unnest(i.indcollation::oid[]) with ordinality
                              as collation_part(collation_oid, ordinality)
                   ) = expected_collations
            ) into index_is_canonical;
            if index_is_canonical is distinct from true then
                raise exception
                    'normalized % receipt history has an incompatible performance index %',
                    index_spec.label, index_spec.index_name;
            end if;
        else
            execute format(
                'create index %I on public.%I (%s)',
                index_spec.index_name,
                index_spec.history_table,
                index_spec.index_sql
            );
        end if;
    end loop;
end
