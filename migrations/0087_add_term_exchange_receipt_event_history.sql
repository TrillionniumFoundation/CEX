-- installing the runtime trigger/backfill path.  These checks are deliberately
-- catalog-based: a partial rollout may have used different constraint names,
-- but it must still provide one global event-id key and one
-- (receipt_id,event_sequence) key for deterministic predecessor selection and
-- idempotent retries.
