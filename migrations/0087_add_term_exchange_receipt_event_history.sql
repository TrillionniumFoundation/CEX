-- Add one independently-owned shape constraint for partial tables that were
-- created without the canonical per-field checks.  The trigger below handles
-- cross-table authority and JSON bindings; this constraint keeps direct SQL
-- inserts fail-closed even when a caller bypasses the trigger with a malformed
-- scalar/hash/status value.
do $history_shape_constraint_guard$
declare
    table_spec record;
    shape_name text;
    shape_oid oid;
begin
    for table_spec in
        select *
          from (values
              ('league_term_exchange_receipt_events_v1'::text, 'league'::text),
              ('world_term_exchange_receipt_events_v1'::text, 'world'::text)
          ) as allowed_tables(history_table, label)
    loop
        shape_name := table_spec.history_table || '_shape_v1';
        select c.oid
          into shape_oid
          from pg_catalog.pg_constraint c
         where c.conrelid = to_regclass('public.' || table_spec.history_table)
           and c.conname = shape_name
           and c.contype = 'c';
        if exists (
            select 1
              from pg_catalog.pg_constraint c
             where c.conrelid = to_regclass('public.' || table_spec.history_table)
               and c.conname = shape_name
               and c.contype <> 'c'
        ) then
            raise exception
                'normalized % receipt history shape object is not a CHECK constraint',
                table_spec.label;
        end if;
        if shape_oid is not null then
            -- A same-named CHECK may have been committed by an interrupted or
            -- manual rollout with an unreachable OR branch containing the
            -- canonical text (or with CHECK (true)).  Text-fragment matching
            -- cannot prove that every conjunct is live.  The pre-existing-row
            -- audit above has already validated all rows, so replace the
            -- object atomically under the table lock and install the exact
            -- canonical predicate for future direct SQL inserts.
            execute format(
                'alter table public.%I drop constraint %I',
                table_spec.history_table, shape_name
            );
        end if;
        execute format(
            'alter table public.%I add constraint %I check (' ||
            'event_id > 0 ' ||
            'and event_sequence > 0 ' ||
            'and (previous_receipt_hash is null or previous_receipt_hash ~ ''^sha256:[0-9a-f]{64}$'') ' ||
            'and receipt_hash ~ ''^sha256:[0-9a-f]{64}$'' ' ||
            'and length(btrim(status)) between 1 and 128 ' ||
            'and progression_class in (''progression_allowed'', ''recoverable_hold'', ''terminal_skip'', ''hard_fail'') ' ||
            'and event_kind in (''initial'', ''backfill'', ''hold'', ''final'', ''transition'') ' ||
            'and (amount_credits is null or amount_credits >= 0) ' ||
            'and jsonb_typeof(receipt_json) = ''object''' ||
            ')',
            table_spec.history_table, shape_name
        );
    end loop;
end
