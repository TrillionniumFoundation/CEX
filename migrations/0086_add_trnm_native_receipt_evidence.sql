create or replace function public.cex_validate_trnm_economic_receipt_event_v1()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $function$
declare
    intent_row record;
    expected_sequence bigint;
    previous_progression text;
    previous_receipt_id text;
    seed_receipt_id text;
    seed_intent_id text;
    bound_intent_id text;
    immutable_amount bigint;
    immutable_amount_present boolean := false;
    immutable_amount_invalid boolean := false;
begin
    if new.event_id is null or new.event_id <= 0 then
        raise exception 'TRNM receipt event event_id must be a positive generated key';
    end if;
    if new.receipt_id is null or btrim(new.receipt_id) = '' then
        raise exception 'TRNM receipt event receipt_id must be non-empty';
    end if;
    -- `_cex_legacy_amount_fallback` is migration-only provenance.  A live
    -- native INSERT must never be able to self-authorize legacy evidence by
    -- copying this reserved key into its JSON envelope.
    if jsonb_typeof(new.receipt_json -> 'evidence') = 'object'
       and (new.receipt_json -> 'evidence') ? '_cex_legacy_amount_fallback' then
        raise exception
            'TRNM legacy amount fallback marker is reserved for migration backfill';
    end if;

    -- Serialize all writers for one receipt identity before reading the
    -- existing stream.  This closes the race in which two different intents
    -- both observe no prior row and attempt to claim the same receipt_id.
    perform pg_advisory_xact_lock(hashtextextended(new.receipt_id, 0));

    select protocol_version,
           idempotency_scope,
           idempotency_key,
           payload_hash,
           intent_json,
           intent_json -> 'term_id' as term_json,
           intent_json -> 'amount_credits' as amount_json
      into intent_row
      from public.trnm_economic_intents
     where intent_id = new.intent_id;
    if not found then
        raise exception 'TRNM receipt event intent binding does not exist';
    end if;
    if intent_row.payload_hash is null
       or intent_row.payload_hash !~ '^[0-9a-f]{64}$' then
        raise exception 'TRNM economic intent payload_hash is not canonical';
    end if;
    if new.intent_hash is distinct from intent_row.payload_hash
       or new.protocol_version is distinct from intent_row.protocol_version
       or new.idempotency_scope is distinct from intent_row.idempotency_scope
       or new.idempotency_key is distinct from intent_row.idempotency_key then
        raise exception 'TRNM receipt event immutable intent binding mismatch';
    end if;
    -- Rows inserted through the native path are later decoded as the typed
    -- EconomicIntent by lookup.  Keep the database boundary aligned with that
    -- decoder for the identity fields that the event envelope copies: JSONB
    -- text operators stringify numbers, so compare only after requiring an
    -- object and string-shaped, non-empty values.
    if jsonb_typeof(intent_row.intent_json) is distinct from 'object'
       or jsonb_typeof(intent_row.intent_json -> 'intent_id') is distinct from 'string'
       or btrim(intent_row.intent_json ->> 'intent_id') = ''
       or intent_row.intent_json ->> 'intent_id' is distinct from new.intent_id
       or jsonb_typeof(intent_row.intent_json -> 'protocol_version') is distinct from 'string'
       or btrim(intent_row.intent_json ->> 'protocol_version') = ''
       or intent_row.intent_json ->> 'protocol_version' is distinct from new.protocol_version then
        raise exception 'TRNM receipt event immutable intent JSON identity is invalid';
    end if;
    if jsonb_typeof(intent_row.term_json) is distinct from 'string'
       or btrim(intent_row.term_json #>> '{}') = '' then
        raise exception 'TRNM receipt event immutable intent term_id is invalid';
    end if;
    -- Older 0027 audit-only rows may omit the nested idempotency object, but a
    -- present value is still part of the EconomicIntent contract.  Reject
    -- numeric/null/array-shaped fields instead of letting `->>` stringify a
    -- forged scope or key into the SQL authority.
    if intent_row.intent_json ? 'idempotency_key'
       and (
           jsonb_typeof(intent_row.intent_json -> 'idempotency_key') is distinct from 'object'
           or jsonb_typeof(intent_row.intent_json #> '{idempotency_key,scope}') is distinct from 'string'
           or jsonb_typeof(intent_row.intent_json #> '{idempotency_key,key}') is distinct from 'string'
           or btrim(intent_row.intent_json #>> '{idempotency_key,scope}') = ''
           or btrim(intent_row.intent_json #>> '{idempotency_key,key}') = ''
           or intent_row.intent_json #>> '{idempotency_key,scope}' is distinct from intent_row.idempotency_scope
           or intent_row.intent_json #>> '{idempotency_key,key}' is distinct from intent_row.idempotency_key
       ) then
        raise exception 'TRNM receipt event immutable intent idempotency JSON is invalid';
    end if;

    -- `amount_credits` is optional only for audit-only intents.  When the key
    -- is present (including an explicit JSON null), it is immutable authority:
    -- it must be a JSON integer and non-negative.  Malformed/negative/null
    -- intent amounts deliberately collapse to zero so a corrupt intent can
    -- never authorize value-bearing evidence.  An omitted key alone permits
    -- the legacy compatibility fallback.
    if intent_row.amount_json is not null then
        immutable_amount_present := true;
        if jsonb_typeof(intent_row.amount_json) <> 'number'
           or (intent_row.amount_json #>> '{}') !~ '^-?[0-9]+$' then
            immutable_amount_invalid := true;
        else
            begin
                immutable_amount := (intent_row.amount_json #>> '{}')::bigint;
            exception when others then
                immutable_amount_invalid := true;
            end;
            if immutable_amount is null or immutable_amount < 0 then
                immutable_amount_invalid := true;
            end if;
        end if;
    end if;
    if immutable_amount_invalid then
        if new.amount_credits is distinct from 0 then
            raise exception 'TRNM receipt event amount is not authorized by an invalid immutable intent amount';
        end if;
    elsif immutable_amount_present
          and new.amount_credits is distinct from immutable_amount then
        raise exception 'TRNM receipt event amount does not match immutable intent amount';
    end if;

    -- Enforce the receipt_id -> intent_id functional dependency for every
    -- append, not only sequence one.  The partial unique index installed by
    -- this migration protects first-event claims; this check covers retries,
    -- pre-existing streams without a first row, and compatibility seeds.
    select e.intent_id
      into bound_intent_id
      from public.trnm_economic_receipt_events_v1 e
     where e.receipt_id = new.receipt_id
     order by e.event_sequence, e.event_id
     limit 1;
    if bound_intent_id is not null
       and bound_intent_id is distinct from new.intent_id then
        raise exception 'TRNM receipt event receipt_id is already bound to a different intent';
    end if;
    select r.intent_id
      into seed_intent_id
      from public.trnm_economic_receipts r
     where r.receipt_id = new.receipt_id;
    if seed_intent_id is not null
       and seed_intent_id is distinct from new.intent_id then
        raise exception 'TRNM receipt event receipt_id conflicts with compatibility receipt intent';
    end if;

    select coalesce(max(event_sequence), 0) + 1
      into expected_sequence
      from public.trnm_economic_receipt_events_v1
     where intent_id = new.intent_id;
    if new.event_sequence is distinct from expected_sequence then
        raise exception 'TRNM receipt event sequence must append the next contiguous snapshot';
    end if;
    if expected_sequence = 1 then
        -- A compatibility seed may already exist when an interrupted 0086
        -- rollout is resumed.  Never let a first event fork that identity.
        select receipt_id
          into seed_receipt_id
          from public.trnm_economic_receipts
         where intent_id = new.intent_id;
        if seed_receipt_id is not null
           and new.receipt_id is distinct from seed_receipt_id then
            raise exception 'TRNM receipt event receipt_id conflicts with immutable compatibility seed';
        end if;
    end if;
    select progression_class, receipt_id
      into previous_progression, previous_receipt_id
      from public.trnm_economic_receipt_events_v1
     where intent_id = new.intent_id
     order by event_sequence desc, event_id desc
     limit 1;
    if expected_sequence > 1
       and new.receipt_id is distinct from previous_receipt_id then
        raise exception 'TRNM receipt event receipt_id must remain stable for an intent';
    end if;
    -- A recoverable hold is the only non-terminal state that may receive a
    -- later snapshot.  Once an attempt has reached an allowed, skipped, or
    -- hard-fail class, accepting another event would permit a terminal result
    -- to be rewritten by a subsequent hold/retry.
    if expected_sequence > 1
       and previous_progression is distinct from 'recoverable_hold' then
        raise exception 'TRNM terminal receipt event cannot append after final progression';
    end if;
    if expected_sequence = 1 and new.event_kind <> 'initial' then
        raise exception 'TRNM receipt event sequence one must be initial';
    end if;
    if expected_sequence > 1 and new.event_kind = 'initial' then
        raise exception 'TRNM receipt retry event cannot be initial';
    end if;
    if previous_progression = 'recoverable_hold'
       and new.event_kind <> 'recoverable_hold_retry' then
        raise exception 'TRNM recoverable-hold retry must be marked as a retry event';
    end if;
    if previous_progression is distinct from 'recoverable_hold'
       and new.event_kind = 'recoverable_hold_retry' then
        raise exception 'TRNM receipt retry event requires a recoverable-hold predecessor';
    end if;
    -- JSONB's text operators stringify numeric scalars.  Require the same
    -- serde-compatible types as EconomicReceipt before comparing values, or a
    -- payload such as `{\"intent_id\":123}` could masquerade as the string
    -- authority `\"123\"`.
    if jsonb_typeof(new.receipt_json -> 'intent_id') is distinct from 'string'
       or jsonb_typeof(new.receipt_json -> 'receipt_id') is distinct from 'string'
       or jsonb_typeof(new.receipt_json -> 'protocol_version') is distinct from 'string'
       or jsonb_typeof(new.receipt_json -> 'term_id') is distinct from 'string'
       or jsonb_typeof(new.receipt_json -> 'backend_id') is distinct from 'string'
       or jsonb_typeof(new.receipt_json -> 'backend_kind') is distinct from 'string'
       or jsonb_typeof(new.receipt_json -> 'status') is distinct from 'string'
       or jsonb_typeof(new.receipt_json -> 'progression_class') is distinct from 'string'
       or (new.receipt_json ? 'settlement_reference'
           and jsonb_typeof(new.receipt_json -> 'settlement_reference') is distinct from 'null'
           and jsonb_typeof(new.receipt_json -> 'settlement_reference') <> 'string')
       or (new.receipt_json ? 'ledger_entry_id'
           and jsonb_typeof(new.receipt_json -> 'ledger_entry_id') is distinct from 'null'
           and jsonb_typeof(new.receipt_json -> 'ledger_entry_id') <> 'string')
       or (new.receipt_json ? 'reason'
           and jsonb_typeof(new.receipt_json -> 'reason') is distinct from 'null'
           and jsonb_typeof(new.receipt_json -> 'reason') <> 'string')
       or jsonb_typeof(new.receipt_json -> 'evidence') is distinct from 'object'
       or jsonb_typeof(new.receipt_json #> '{evidence,payload_hash}') is distinct from 'string'
       or new.receipt_json #>> '{evidence,payload_hash}' !~ '^[0-9a-f]{64}$'
       or new.receipt_json ->> 'intent_id' is distinct from new.intent_id
       or new.receipt_json ->> 'receipt_id' is distinct from new.receipt_id
       or new.receipt_json ->> 'protocol_version' is distinct from new.protocol_version
       or new.receipt_json ->> 'term_id' is distinct from intent_row.term_json #>> '{}'
       or new.receipt_json ->> 'backend_id' is distinct from 'cex-settlement-backend'
       or new.receipt_json ->> 'backend_kind' is distinct from 'cex'
       or new.receipt_json #>> '{evidence,payload_hash}' is distinct from new.intent_hash
       or jsonb_typeof(new.receipt_json #> '{evidence,amount_credits}') is distinct from 'number'
       or (new.receipt_json #>> '{evidence,amount_credits}') !~ '^-?[0-9]+$'
       or coalesce(new.receipt_json #> '{evidence,amount_credits}', 'null'::jsonb)
          is distinct from to_jsonb(new.amount_credits)
       or new.receipt_json ->> 'status' is distinct from new.status
       or new.receipt_json ->> 'progression_class' is distinct from new.progression_class then
        raise exception 'TRNM receipt event JSON binding mismatch';
    end if;
    if not (new.receipt_json ? 'finalized_at_epoch')
       or jsonb_typeof(new.receipt_json -> 'finalized_at_epoch') is distinct from 'number'
       or (new.receipt_json ->> 'finalized_at_epoch') !~ '^-?[0-9]+$'
       or (new.receipt_json ->> 'finalized_at_epoch')::numeric
            is distinct from (extract(epoch from new.finalized_at)::bigint)::numeric then
        raise exception 'TRNM receipt event finalized_at_epoch binding mismatch';
    end if;
    if (case
            when new.status in (
                'reserved', 'settled', 'reopened_settled', 'consumed', 'refunded',
                'seller_chargeback_reserved', 'seller_chargeback_consumed',
                'approved_release', 'duplicate'
            ) then 'progression_allowed'
            when new.status in (
                'skipped_zero_price', 'skipped_zero_reward', 'skipped_zero_seller_net'
            ) then 'terminal_skip'
            when new.status in (
                'held_review', 'skipped_missing_room', 'failed_network', 'failed_identity',
                'failed_ledger', 'seller_chargeback_reserve_failed',
                'seller_chargeback_failed', 'rejected_refund_failed',
                'cancelled_refund_failed'
            ) then 'recoverable_hold'
            when new.status in (
                'failed_bad_response', 'skipped_missing_account',
                'skipped_missing_ledger_token', 'missing_account', 'missing_ledger_token'
            ) then 'hard_fail'
            else null
        end) is distinct from new.progression_class then
        raise exception 'TRNM receipt status/progression mapping mismatch';
    end if;
    if new.receipt_hash is distinct from
       encode(digest(new.receipt_json::text, 'sha256'), 'hex') then
        raise exception 'TRNM receipt event hash mismatch';
    end if;
    return new;
end
$function$;

