-- Backfill the first immutable snapshot for rows written by 0027.  Resolve
-- the amount with the same immutable-intent-first precedence used above before
-- constructing the JSON/hash.  The NOT-EXISTS guard makes the expand migration
-- safe to replay on a partially upgraded database.
with legacy_rows as (
    select r.intent_id,
           r.receipt_id,
           r.protocol_version,
           r.idempotency_scope,
           r.idempotency_key,
           r.progression_class,
           r.status,
           r.receipt_json,
           r.finalized_at,
           r.created_at,
           i.payload_hash,
           public.cex_trnm_nonnegative_bigint_or_null_v1(
               r.receipt_json #>> '{evidence,amount_credits}'
           ) as evidence_amount,
           public.cex_trnm_nonnegative_bigint_or_null_v1(
               i.intent_json ->> 'amount_credits'
           ) as intent_amount,
           coalesce(
               (i.intent_json ? 'amount_credits')
                   and jsonb_typeof(i.intent_json -> 'amount_credits') <> 'null',
               false
           ) as intent_amount_present,
           coalesce(
               (i.intent_json ? 'amount_credits')
                   and jsonb_typeof(i.intent_json -> 'amount_credits') = 'number'
                   and public.cex_trnm_nonnegative_bigint_or_null_v1(
                       i.intent_json ->> 'amount_credits'
                   ) is not null,
               false
           ) as intent_amount_valid
      from public.trnm_economic_receipts r
      join public.trnm_economic_intents i using (intent_id)
), resolved_rows as (
    select legacy_rows.*,
           case
               when intent_amount_valid then intent_amount
               when intent_amount_present then 0
               else coalesce(evidence_amount, 0)
           end as resolved_amount
      from legacy_rows
), normalized_rows as (
    select resolved_rows.*,
           public.cex_trnm_normalize_receipt_json_v1(
               receipt_json,
               intent_id,
               receipt_id,
               protocol_version,
               status,
               progression_class,
               payload_hash,
               resolved_amount
           ) as normalized_receipt_json
      from resolved_rows
)
insert into public.trnm_economic_receipt_events_v1 (
    intent_id, event_sequence, intent_hash, receipt_id, protocol_version,
    idempotency_scope, idempotency_key, progression_class, status, amount_credits, receipt_json,
    receipt_hash, event_kind, finalized_at, created_at
)
select normalized_rows.intent_id,
       1,
       normalized_rows.payload_hash,
       normalized_rows.receipt_id,
       normalized_rows.protocol_version,
       normalized_rows.idempotency_scope,
       normalized_rows.idempotency_key,
       normalized_rows.progression_class,
       normalized_rows.status,
       normalized_rows.resolved_amount,
       normalized_rows.normalized_receipt_json,
       encode(digest(normalized_rows.normalized_receipt_json::text, 'sha256'), 'hex'),
       'initial',
       normalized_rows.finalized_at,
       normalized_rows.created_at
  from normalized_rows
 where not exists (
           select 1
             from public.trnm_economic_receipt_events_v1 e
            where e.intent_id = normalized_rows.intent_id
             and e.event_sequence = 1
       );

-- Existing rows were present before the INSERT trigger was installed.  Verify
-- them explicitly after compatibility normalization so a conflicting legacy
-- field cannot survive merely because it was not missing.
do $validation$
begin
    if exists (
        select 1
          from public.trnm_economic_receipt_events_v1 e
          join public.trnm_economic_intents i using (intent_id)
         where e.receipt_json ->> 'intent_id' is distinct from e.intent_id
            or e.receipt_json ->> 'receipt_id' is distinct from e.receipt_id
            or e.receipt_json ->> 'protocol_version' is distinct from e.protocol_version
            or e.receipt_json ->> 'status' is distinct from e.status
            or e.receipt_json ->> 'progression_class' is distinct from e.progression_class
            or e.receipt_json #>> '{evidence,payload_hash}' is distinct from e.intent_hash
            or jsonb_typeof(e.receipt_json #> '{evidence,amount_credits}') is distinct from 'number'
            or (e.receipt_json #>> '{evidence,amount_credits}') !~ '^-?[0-9]+$'
            or coalesce(e.receipt_json #> '{evidence,amount_credits}', 'null'::jsonb)
               is distinct from to_jsonb(e.amount_credits)
            or e.receipt_hash is distinct from
               encode(digest(e.receipt_json::text, 'sha256'), 'hex')
            or (
                (i.intent_json ? 'amount_credits')
                and jsonb_typeof(i.intent_json -> 'amount_credits') <> 'null'
                and (
                    (
                        jsonb_typeof(i.intent_json -> 'amount_credits') = 'number'
                        and (i.intent_json ->> 'amount_credits') ~ '^-?[0-9]+$'
                        and public.cex_trnm_nonnegative_bigint_or_null_v1(
                            i.intent_json ->> 'amount_credits'
                        ) is not null
                        and e.amount_credits is distinct from
                            public.cex_trnm_nonnegative_bigint_or_null_v1(
                                i.intent_json ->> 'amount_credits'
                            )
                    )
                    or (
                        (
                            jsonb_typeof(i.intent_json -> 'amount_credits') <> 'number'
                            or (i.intent_json ->> 'amount_credits') !~ '^-?[0-9]+$'
                            or public.cex_trnm_nonnegative_bigint_or_null_v1(
                                i.intent_json ->> 'amount_credits'
                            ) is null
                        )
                        and e.amount_credits is distinct from 0
                    )
                )
            )
    ) then
        raise exception 'TRNM legacy receipt evidence failed compatibility validation';
    end if;
    if exists (
        select 1
          from public.trnm_economic_receipt_events_v1 e
          join public.trnm_economic_receipts r using (intent_id)
         where e.event_sequence = 1
           and e.receipt_id is distinct from r.receipt_id
    ) then
        raise exception 'TRNM native receipt history/seed receipt_id conflict';
    end if;
    if exists (
        select 1
          from public.trnm_economic_receipt_events_v1
         group by intent_id
        having count(distinct receipt_id) > 1
    ) then
        raise exception 'TRNM native receipt history contains multiple receipt_ids for one intent';
    end if;
end
$validation$;

