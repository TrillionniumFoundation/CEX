-- Never let malformed/overflowing legacy JSON abort the migration.  Invalid
-- evidence is normalized to NULL and then to zero, which remains explicitly
-- non-progressing at every value-bearing consumer.  The helper is removed at
-- the end of this migration; it is not part of the runtime API.
create or replace function public.cex_trnm_nonnegative_bigint_or_null_v1(raw_value text)
returns bigint
language plpgsql
set search_path = pg_catalog, public
as $function$
declare
    parsed_value bigint;
begin
    if raw_value is null or btrim(raw_value) = '' then
        return null;
    end if;
    begin
        parsed_value := raw_value::bigint;
    exception when others then
        return null;
    end;
    -- A negative amount is invalid evidence, not a legitimate zero.  Return
    -- NULL so the caller can fall through to the immutable intent (or the
    -- already-stored non-negative projection) instead of clobbering a real
    -- positive amount with a synthetic zero.
    if parsed_value < 0 then
        return null;
    end if;
    return parsed_value;
end
$function$;

-- Evidence is a JSON contract, not a free-form text field.  The text helper
-- above is intentionally retained for immutable-intent extraction (where the
-- caller performs the JSON type check); evidence callers must go through this
-- wrapper so a numeric-looking JSON string, decimal, object, array, or JSON
-- null cannot be promoted to a value-bearing amount during compatibility
-- repair.  Negative/overflowing integers remain invalid and return NULL via
-- the shared non-negative bigint parser.
create or replace function public.cex_trnm_nonnegative_jsonb_bigint_or_null_v1(raw_value jsonb)
returns bigint
language plpgsql
set search_path = pg_catalog, public
as $function$
declare
    raw_text text;
begin
    if raw_value is null
       or jsonb_typeof(raw_value) is distinct from 'number' then
        return null;
    end if;
    raw_text := raw_value #>> '{}';
    if raw_text is null or raw_text !~ '^-?[0-9]+$' then
        return null;
    end if;
    return public.cex_trnm_nonnegative_bigint_or_null_v1(raw_text);
end
$function$;

-- Normalize legacy JSON identity fields only where they are absent.  Conflicting
-- identity/status/hash fields are deliberately preserved so the validation
-- trigger (and the explicit post-backfill check below) can reject tampered or
-- forked evidence instead of silently rewriting it.  Amount evidence is the
-- one intentional compatibility repair: when immutable intent.amount_credits
-- is valid, it is canonicalized below so an old, stale amount cannot authorize
-- a different value; new writes still reject any mismatch.
create or replace function public.cex_trnm_normalize_receipt_json_v1(
    raw_value jsonb,
    expected_intent_id text,
    expected_receipt_id text,
    expected_protocol_version text,
    expected_term_id text,
    expected_status text,
    expected_progression_class text,
    expected_payload_hash text,
    resolved_amount bigint,
    expected_finalized_at_epoch bigint
)
returns jsonb
language plpgsql
immutable
set search_path = pg_catalog, public
as $function$
declare
    normalized jsonb;
begin
    -- Missing JSON is not an authority we can reconstruct.  Return malformed
    -- scalar/array/NULL values untouched so the insert/post-backfill guards
    -- reject them; only an actual object is eligible for additive completion
    -- of legacy fields.
    if raw_value is null
       or jsonb_typeof(raw_value) is distinct from 'object' then
        return raw_value;
    end if;
    normalized := raw_value;
    -- Treat a key as missing only when it is genuinely absent.  `->>`
    -- returns SQL NULL for both an absent key and an explicit JSON null;
    -- silently replacing the latter would turn malformed evidence into a
    -- trusted snapshot instead of letting the post-backfill validator reject
    -- it.
    if not (normalized ? 'intent_id') then
        normalized := jsonb_set(normalized, '{intent_id}', to_jsonb(expected_intent_id), true);
    end if;
    if not (normalized ? 'receipt_id') then
        normalized := jsonb_set(normalized, '{receipt_id}', to_jsonb(expected_receipt_id), true);
    end if;
    if not (normalized ? 'protocol_version') then
        normalized := jsonb_set(normalized, '{protocol_version}', to_jsonb(expected_protocol_version), true);
    end if;
    if expected_term_id is not null and not (normalized ? 'term_id') then
        normalized := jsonb_set(normalized, '{term_id}', to_jsonb(expected_term_id), true);
    end if;
    if not (normalized ? 'status') then
        normalized := jsonb_set(normalized, '{status}', to_jsonb(expected_status), true);
    end if;
    if not (normalized ? 'progression_class') then
        normalized := jsonb_set(normalized, '{progression_class}', to_jsonb(expected_progression_class), true);
    end if;
    -- An absent evidence object is a legacy shape we can safely complete.  An
    -- explicitly present non-object (including JSON null) is malformed and is
    -- left untouched so the validation pass below fails closed.
    if not (normalized ? 'evidence') then
        normalized := jsonb_set(normalized, '{evidence}', '{}'::jsonb, true);
    end if;
    -- `jsonb_set` treats a scalar/array parent as an invalid array/object
    -- path and raises before the explicit post-backfill validator can report
    -- the malformed evidence.  Only descend into a real object; a present
    -- non-object is intentionally preserved so the validator rejects it
    -- without a low-level path error or accidental coercion.
    if jsonb_typeof(normalized -> 'evidence') = 'object' then
        normalized := jsonb_set(
            normalized,
            '{evidence,amount_credits}',
            to_jsonb(coalesce(resolved_amount, 0)),
            true
        );
        if not (normalized -> 'evidence' ? 'payload_hash') then
            normalized := jsonb_set(
                normalized,
                '{evidence,payload_hash}',
                to_jsonb(expected_payload_hash),
                true
            );
        end if;
    end if;
    -- Native receipts are emitted by the CEX backend and EconomicReceipt has
    -- required backend/finalization fields.  Add only genuinely absent keys
    -- during the compatibility upgrade; explicit NULL or conflicting values
    -- remain untouched so the post-backfill audit rejects them.
    if not (normalized ? 'backend_id') then
        normalized := jsonb_set(normalized, '{backend_id}', '"cex-settlement-backend"'::jsonb, true);
    end if;
    if not (normalized ? 'backend_kind') then
        normalized := jsonb_set(normalized, '{backend_kind}', '"cex"'::jsonb, true);
    end if;
    if expected_finalized_at_epoch is not null and not (normalized ? 'finalized_at_epoch') then
        normalized := jsonb_set(
            normalized,
            '{finalized_at_epoch}',
            to_jsonb(expected_finalized_at_epoch),
            true
        );
    end if;
    return normalized;
end
$function$;

-- Preserve provenance for the one compatibility case that can recover a
-- positive amount without an immutable `amount_credits` key.  Native/live
-- writers use the same receipt JSON shape but must never be allowed to claim
-- that legacy evidence authority, so lookup requires this reserved marker
-- when the native event stream is selected.  Existing non-marker values are
-- left untouched: a pre-existing conflicting marker remains a corrupt binding
-- instead of being silently upgraded during retry.  The marker is applied
-- only by the legacy-projection INSERT below; rows already present in the
-- native event table are not granted new authority merely from their shape.
create or replace function public.cex_trnm_mark_legacy_amount_fallback_v1(
    raw_value jsonb,
    should_mark boolean
)
returns jsonb
language plpgsql
immutable
set search_path = pg_catalog, public
as $function$
begin
    if not coalesce(should_mark, false)
       or raw_value is null
       or jsonb_typeof(raw_value) is distinct from 'object'
       or jsonb_typeof(raw_value -> 'evidence') is distinct from 'object'
       or (raw_value -> 'evidence') ? '_cex_legacy_amount_fallback' then
        return raw_value;
    end if;
    return jsonb_set(
        raw_value,
        '{evidence,_cex_legacy_amount_fallback}',
        'true'::jsonb,
        true
    );
end
$function$;

-- A JSON marker alone cannot distinguish a row created by this migration from
-- a pre-existing native row that copied the same legacy-looking envelope.  Keep
-- a small, append-only provenance ledger for the compatibility exception.  It
-- is populated only from the INSERT ... RETURNING batch below and is checked
-- again on retries, so a successful first run remains replayable without
-- granting authority to a row that merely happens to have the marker.

-- `CREATE TABLE IF NOT EXISTS` emits only a notice when a relation with the
-- requested name already exists.  A view/sequence/foreign table at this name
-- is not a partially-applied provenance ledger that can be repaired safely;
-- reject it before the CREATE statement so the failure is explicit and the
-- transaction leaves the pre-existing object untouched.
do $legacy_provenance_relation_guard$
declare
    relation_kind text;
begin
    select c.relkind::text
      into relation_kind
      from pg_catalog.pg_class c
      join pg_catalog.pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public'
       and c.relname = 'trnm_economic_receipt_legacy_fallback_provenance_v1';
    if found and relation_kind <> 'r' then
        raise exception
            'TRNM legacy fallback provenance name is occupied by a non-table relation';
    end if;
end
$legacy_provenance_relation_guard$;

create table if not exists public.trnm_economic_receipt_legacy_fallback_provenance_v1 (
