-- `INSERT` triggers cannot validate rows that were committed by an interrupted
-- rollout before the trigger existed.  The compatibility pass above repairs
-- only the documented missing amount/evidence fields; this independent audit
-- now validates the complete native stream before it is exposed as durable
-- authority.  Keep this check after normalization so an old row with omitted
-- identity/evidence keys remains repairable, while explicit non-canonical
-- scalar values (and all immutable column bindings) fail closed.
do $native_history_semantics_guard$
declare
    event_row record;
    previous_intent_id text;
    previous_receipt_id text;
    previous_intent_hash text;
    previous_protocol_version text;
    previous_idempotency_scope text;
    previous_idempotency_key text;
    previous_progression_class text;
    previous_event_sequence bigint;
    previous_amount_credits bigint;
    have_previous boolean := false;
    expected_progression text;
begin
    for event_row in
        select e.event_id,
               e.intent_id,
               e.event_sequence,
               e.intent_hash,
               e.receipt_id,
               e.protocol_version,
               e.idempotency_scope,
               e.idempotency_key,
               e.progression_class,
               e.status,
               e.amount_credits,
               e.receipt_json,
               e.receipt_hash,
               e.event_kind,
               e.finalized_at,
               e.created_at,
               i.payload_hash as authority_payload_hash,
               i.protocol_version as authority_protocol_version,
               i.intent_json as authority_intent_json,
               i.intent_json ->> 'term_id' as authority_term_id,
               i.idempotency_scope as authority_idempotency_scope,
               i.idempotency_key as authority_idempotency_key
          from public.trnm_economic_receipt_events_v1 e
          join public.trnm_economic_intents i
            on i.intent_id = e.intent_id
         order by e.intent_id, e.event_sequence, e.event_id
    loop
        -- Key/scalar checks are repeated here even when a canonical check
        -- constraint happened to exist: `CREATE TABLE IF NOT EXISTS` does not
        -- prove that a partial runner used the canonical expression.
        if event_row.event_id is null or event_row.event_id <= 0 then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: event_id is invalid';
        end if;
        if event_row.intent_id is null or btrim(event_row.intent_id) = '' then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: intent_id is blank';
        end if;
        if event_row.receipt_id is null or btrim(event_row.receipt_id) = '' then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: receipt_id is blank';
        end if;
        if event_row.event_sequence is null or event_row.event_sequence <= 0 then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: event_sequence is invalid';
        end if;
        if event_row.intent_hash is null
           or event_row.intent_hash !~ '^[0-9a-f]{64}$' then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: intent_hash is invalid';
        end if;
        if event_row.receipt_hash is null
           or event_row.receipt_hash !~ '^[0-9a-f]{64}$' then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: receipt_hash is invalid';
        end if;
        if event_row.protocol_version is null
           or btrim(event_row.protocol_version) = ''
           or event_row.idempotency_scope is null
           or btrim(event_row.idempotency_scope) = ''
           or event_row.idempotency_key is null
           or btrim(event_row.idempotency_key) = '' then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: immutable identity is blank';
        end if;
        if event_row.progression_class is null
           or event_row.progression_class not in (
               'progression_allowed', 'recoverable_hold', 'terminal_skip', 'hard_fail'
           ) then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: progression_class is invalid';
        end if;
        if event_row.status is null
           or length(btrim(event_row.status)) not between 1 and 128 then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: status is invalid';
        end if;
        if event_row.amount_credits is null or event_row.amount_credits < 0 then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: amount_credits is invalid';
        end if;
        if event_row.event_kind is null
           or event_row.event_kind not in ('initial', 'recoverable_hold_retry', 'progression') then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: event_kind is invalid';
        end if;
        if event_row.finalized_at is null or event_row.created_at is null then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: timestamp is NULL';
        end if;
        if event_row.receipt_json is null
           or jsonb_typeof(event_row.receipt_json) is distinct from 'object' then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: receipt_json is not an object';
        end if;

        -- The event trigger validates the intent term for newly inserted rows,
        -- but rows committed by an interrupted rollout predate that trigger.
        -- Do not let JSONB's text operators turn a numeric/object-shaped
        -- immutable intent field into a string authority.  The top-level
        -- identity fields are present in every supported 0027 intent shape;
        -- nested typed fields remain owned by the service decoder so this
        -- compatibility migration does not rewrite legacy intent bytes.
        if jsonb_typeof(event_row.authority_intent_json) is distinct from 'object'
           or jsonb_typeof(event_row.authority_intent_json -> 'intent_id') is distinct from 'string'
           or btrim(event_row.authority_intent_json ->> 'intent_id') = ''
           or event_row.authority_intent_json ->> 'intent_id' is distinct from event_row.intent_id
           or jsonb_typeof(event_row.authority_intent_json -> 'protocol_version') is distinct from 'string'
           or btrim(event_row.authority_intent_json ->> 'protocol_version') = ''
           or event_row.authority_intent_json ->> 'protocol_version' is distinct from event_row.protocol_version then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: immutable intent JSON identity is invalid';
        end if;
        if jsonb_typeof(event_row.authority_intent_json -> 'term_id') is distinct from 'string'
           or btrim(event_row.authority_intent_json ->> 'term_id') = ''
           or event_row.authority_intent_json ->> 'term_id' is distinct from event_row.authority_term_id then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: immutable intent term_id is invalid';
        end if;
        if event_row.authority_intent_json ? 'idempotency_key'
           and (
               jsonb_typeof(event_row.authority_intent_json -> 'idempotency_key') is distinct from 'object'
               or jsonb_typeof(event_row.authority_intent_json #> '{idempotency_key,scope}') is distinct from 'string'
               or jsonb_typeof(event_row.authority_intent_json #> '{idempotency_key,key}') is distinct from 'string'
               or btrim(event_row.authority_intent_json #>> '{idempotency_key,scope}') = ''
               or btrim(event_row.authority_intent_json #>> '{idempotency_key,key}') = ''
               or event_row.authority_intent_json #>> '{idempotency_key,scope}' is distinct from event_row.authority_idempotency_scope
               or event_row.authority_intent_json #>> '{idempotency_key,key}' is distinct from event_row.authority_idempotency_key
           ) then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: immutable intent idempotency JSON is invalid';
        end if;

        -- The immutable intent row is the authority for all fields copied into
        -- the event envelope.  This is intentionally a field-by-field check,
        -- not a SQL digest of jsonb text: Rust hashes the exact serde JSON
        -- bytes, whose formatting/order is not equivalent to PostgreSQL's
        -- jsonb textual representation.
        if event_row.intent_hash is distinct from event_row.authority_payload_hash
           or event_row.protocol_version is distinct from event_row.authority_protocol_version
           or event_row.authority_term_id is null
           or btrim(event_row.authority_term_id) = ''
           or event_row.idempotency_scope is distinct from event_row.authority_idempotency_scope
           or event_row.idempotency_key is distinct from event_row.authority_idempotency_key then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: immutable intent binding mismatch';
        end if;

        -- Keep a useful diagnostic for an explicitly unknown backend while
        -- still requiring the native stream's canonical CEX backend below.
        if jsonb_typeof(event_row.receipt_json -> 'backend_kind') = 'string'
           and event_row.receipt_json ->> 'backend_kind' not in ('cex') then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: backend_kind is unknown';
        end if;

        -- Required JSON bindings are typed explicitly.  The normalizer fills
        -- absent keys, but it never gets to turn a present number/object into
        -- a string authority (the pre-normalization guard rejects that case).
        if jsonb_typeof(event_row.receipt_json -> 'intent_id') is distinct from 'string'
           or jsonb_typeof(event_row.receipt_json -> 'receipt_id') is distinct from 'string'
           or jsonb_typeof(event_row.receipt_json -> 'protocol_version') is distinct from 'string'
           or jsonb_typeof(event_row.receipt_json -> 'term_id') is distinct from 'string'
           or jsonb_typeof(event_row.receipt_json -> 'backend_id') is distinct from 'string'
           or jsonb_typeof(event_row.receipt_json -> 'backend_kind') is distinct from 'string'
           or jsonb_typeof(event_row.receipt_json -> 'status') is distinct from 'string'
           or jsonb_typeof(event_row.receipt_json -> 'progression_class') is distinct from 'string'
           or event_row.receipt_json ->> 'intent_id' is distinct from event_row.intent_id
           or event_row.receipt_json ->> 'receipt_id' is distinct from event_row.receipt_id
           or event_row.receipt_json ->> 'protocol_version' is distinct from event_row.protocol_version
           or event_row.receipt_json ->> 'term_id' is distinct from event_row.authority_term_id
           or event_row.receipt_json ->> 'backend_id' is distinct from 'cex-settlement-backend'
           or event_row.receipt_json ->> 'backend_kind' is distinct from 'cex'
           or event_row.receipt_json ->> 'status' is distinct from event_row.status
           or event_row.receipt_json ->> 'progression_class' is distinct from event_row.progression_class then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: JSON identity binding mismatch';
        end if;
        if jsonb_typeof(event_row.receipt_json #> '{evidence}') is distinct from 'object'
           or jsonb_typeof(event_row.receipt_json #> '{evidence,payload_hash}') is distinct from 'string'
           or event_row.receipt_json #>> '{evidence,payload_hash}' !~ '^[0-9a-f]{64}$'
           or event_row.receipt_json #>> '{evidence,payload_hash}' is distinct from event_row.intent_hash
           or jsonb_typeof(event_row.receipt_json #> '{evidence,amount_credits}') is distinct from 'number'
           or (event_row.receipt_json #>> '{evidence,amount_credits}') !~ '^-?[0-9]+$'
           or event_row.receipt_json #> '{evidence,amount_credits}' is distinct from to_jsonb(event_row.amount_credits) then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: JSON evidence binding mismatch';
        end if;

        -- Optional EconomicReceipt fields are not represented as native table
        -- columns.  They may be absent/JSON null, but a present non-string
        -- value could not deserialize as the Rust receipt contract.
        if (event_row.receipt_json ? 'settlement_reference'
               and jsonb_typeof(event_row.receipt_json -> 'settlement_reference') is distinct from 'null'
               and jsonb_typeof(event_row.receipt_json -> 'settlement_reference') <> 'string')
           or (event_row.receipt_json ? 'ledger_entry_id'
               and jsonb_typeof(event_row.receipt_json -> 'ledger_entry_id') is distinct from 'null'
               and jsonb_typeof(event_row.receipt_json -> 'ledger_entry_id') <> 'string')
           or (event_row.receipt_json ? 'reason'
               and jsonb_typeof(event_row.receipt_json -> 'reason') is distinct from 'null'
               and jsonb_typeof(event_row.receipt_json -> 'reason') <> 'string') then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: optional receipt JSON field has an incompatible type';
        end if;
        if not (event_row.receipt_json ? 'finalized_at_epoch')
           or jsonb_typeof(event_row.receipt_json -> 'finalized_at_epoch') is distinct from 'number'
           or (event_row.receipt_json ->> 'finalized_at_epoch') !~ '^-?[0-9]+$'
           or (event_row.receipt_json ->> 'finalized_at_epoch')::numeric
                is distinct from (extract(epoch from event_row.finalized_at)::bigint)::numeric then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: finalized_at_epoch is invalid';
        end if;

        if event_row.receipt_hash is distinct from
           encode(digest(event_row.receipt_json::text, 'sha256'), 'hex') then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: receipt_hash digest mismatch';
        end if;

        expected_progression := case
            when event_row.status in (
                'reserved', 'settled', 'reopened_settled', 'consumed', 'refunded',
                'seller_chargeback_reserved', 'seller_chargeback_consumed',
                'approved_release', 'duplicate'
            ) then 'progression_allowed'
            when event_row.status in (
                'skipped_zero_price', 'skipped_zero_reward', 'skipped_zero_seller_net'
            ) then 'terminal_skip'
            when event_row.status in (
                'held_review', 'skipped_missing_room', 'failed_network', 'failed_identity',
                'failed_ledger', 'seller_chargeback_reserve_failed',
                'seller_chargeback_failed', 'rejected_refund_failed',
                'cancelled_refund_failed'
            ) then 'recoverable_hold'
            when event_row.status in (
                'failed_bad_response', 'skipped_missing_account',
                'skipped_missing_ledger_token', 'missing_account', 'missing_ledger_token'
            ) then 'hard_fail'
            else null
        end;
        if expected_progression is null
           or expected_progression is distinct from event_row.progression_class then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: status/progression mapping mismatch';
        end if;

        -- Validate the append chain in deterministic order.  Event-id gaps are
        -- harmless (identity sequences can gap on rolled-back transactions),
        -- but per-intent event_sequence gaps, receipt-id changes, or a
        -- successor after a terminal state would make recovery ambiguous.
        if not have_previous or event_row.intent_id is distinct from previous_intent_id then
            if event_row.event_sequence <> 1
               or event_row.event_kind <> 'initial' then
                raise exception
                    'TRNM native receipt history failed pre-existing-row validation: first event is not a valid sequence-one seed';
            end if;
            have_previous := true;
        else
            if previous_event_sequence = 9223372036854775807
               or event_row.event_sequence <> previous_event_sequence + 1 then
                raise exception
                    'TRNM native receipt history failed pre-existing-row validation: event sequence is not contiguous';
            end if;
            if event_row.receipt_id is distinct from previous_receipt_id then
                raise exception
                    'TRNM native receipt history failed pre-existing-row validation: receipt_id changed across chain';
            end if;
            if previous_progression_class is distinct from 'recoverable_hold' then
                raise exception
                    'TRNM native receipt history failed pre-existing-row validation: terminal event has a successor';
            end if;
            if event_row.event_kind = 'initial' then
                raise exception
                    'TRNM native receipt history failed pre-existing-row validation: retry event is marked initial';
            end if;
            if previous_progression_class = 'recoverable_hold'
               and event_row.event_kind <> 'recoverable_hold_retry' then
                raise exception
                    'TRNM native receipt history failed pre-existing-row validation: recoverable hold successor is not marked retry';
            end if;
            if previous_progression_class is distinct from 'recoverable_hold'
               and event_row.event_kind = 'recoverable_hold_retry' then
                raise exception
                    'TRNM native receipt history failed pre-existing-row validation: retry event lacks recoverable-hold predecessor';
            end if;
            if event_row.intent_hash is distinct from previous_intent_hash
               or event_row.protocol_version is distinct from previous_protocol_version
               or event_row.idempotency_scope is distinct from previous_idempotency_scope
               or event_row.idempotency_key is distinct from previous_idempotency_key
               or event_row.amount_credits is distinct from previous_amount_credits then
                raise exception
                    'TRNM native receipt history failed pre-existing-row validation: immutable identity changed across chain';
            end if;
        end if;

        previous_intent_id := event_row.intent_id;
        previous_receipt_id := event_row.receipt_id;
        previous_intent_hash := event_row.intent_hash;
        previous_protocol_version := event_row.protocol_version;
        previous_idempotency_scope := event_row.idempotency_scope;
        previous_idempotency_key := event_row.idempotency_key;
        previous_progression_class := event_row.progression_class;
        previous_event_sequence := event_row.event_sequence;
        previous_amount_credits := event_row.amount_credits;
    end loop;

    if exists (
        select 1
          from public.trnm_economic_receipt_events_v1
         group by receipt_id
        having count(distinct intent_id) > 1
    ) then
        raise exception
            'TRNM native receipt history failed pre-existing-row validation: receipt_id binds multiple intents';
    end if;
    if exists (
        select 1
          from public.trnm_economic_receipt_events_v1
         group by intent_id
        having count(distinct receipt_id) > 1
    ) then
        raise exception
            'TRNM native receipt history failed pre-existing-row validation: intent_id binds multiple receipt_ids';
    end if;
end
$native_history_semantics_guard$;

-- Runtime inserts omit event_id, so a partial table with a plain primary-key
-- bigint but no identity/serial default would pass the row audit and then fail
-- on the first real append.  Require an owned, monotonic, non-cycling bigint
-- sequence and fail closed when its state is behind manually supplied ids.
-- Sequence gaps themselves are harmless; unlike event_sequence they do not
-- encode receipt progression and therefore are not required to be contiguous.
do $native_event_id_sequence_guard$
declare
    event_table oid := 'public.trnm_economic_receipt_events_v1'::regclass;
    event_attnum smallint;
    event_identity text;
    event_default_oid oid;
    event_default text;
    sequence_qualified text;
    sequence_oid oid;
    sequence_type oid;
    sequence_increment bigint;
    sequence_max bigint;
    sequence_min bigint;
    sequence_cycle boolean;
    sequence_last bigint;
    sequence_called boolean;
    max_event_id bigint;
begin
    select a.attnum,
           a.attidentity::text,
           ad.oid,
           coalesce(pg_get_expr(ad.adbin, ad.adrelid), '')
      into event_attnum, event_identity, event_default_oid, event_default
      from pg_catalog.pg_attribute a
      left join pg_catalog.pg_attrdef ad
        on ad.adrelid = a.attrelid
       and ad.adnum = a.attnum
     where a.attrelid = event_table
       and a.attname = 'event_id'
       and not a.attisdropped;
    if event_attnum is null then
        raise exception 'TRNM native receipt event event_id column is missing';
    end if;
    if coalesce(event_identity, '') = ''
       and event_default_oid is null then
        raise exception
            'TRNM native receipt event event_id has no identity or sequence default';
    end if;
    if coalesce(event_identity, '') = ''
       and regexp_replace(lower(event_default), '[[:space:]]+', '', 'g')
           !~ '^nextval\(.+\)$' then
        raise exception
            'TRNM native receipt event event_id has an unsafe default';
    end if;

    sequence_qualified := pg_get_serial_sequence(
        'public.trnm_economic_receipt_events_v1',
        'event_id'
    );
    if sequence_qualified is null then
        raise exception
            'TRNM native receipt event event_id default has no owned sequence';
    end if;
    sequence_oid := to_regclass(sequence_qualified);
    if sequence_oid is null then
        raise exception
            'TRNM native receipt event event_id sequence is missing';
    end if;
    select s.seqtypid, s.seqincrement, s.seqmax, s.seqmin, s.seqcycle
      into sequence_type, sequence_increment, sequence_max,
           sequence_min, sequence_cycle
      from pg_catalog.pg_sequence s
     where s.seqrelid = sequence_oid;
    if not found
       or sequence_type <> 'int8'::regtype
       or sequence_increment <= 0
       or sequence_min < 1
       or sequence_cycle then
        raise exception
            'TRNM native receipt event event_id sequence is unsafe';
    end if;
    if not exists (
        select 1
          from pg_catalog.pg_depend d
         where d.classid = 'pg_catalog.pg_class'::regclass
           and d.objid = sequence_oid
           and d.refclassid = 'pg_catalog.pg_class'::regclass
           and d.refobjid = event_table
           and d.refobjsubid = event_attnum
           and d.deptype in ('a', 'i')
    ) then
        raise exception
            'TRNM native receipt event event_id sequence is not owned by event_id';
    end if;
    -- Ownership alone does not prove that this is a private generator: a
    -- second column may still carry a normal dependency from DEFAULT
    -- nextval().  Reject that shared state before accepting the partial table.
    if exists (
        select 1
          from pg_catalog.pg_depend d
          join pg_catalog.pg_attrdef ad on ad.oid = d.objid
         where d.classid = 'pg_catalog.pg_attrdef'::regclass
           and d.refclassid = 'pg_catalog.pg_class'::regclass
           and d.refobjid = sequence_oid
           and not (ad.adrelid = event_table and ad.adnum = event_attnum)
    ) then
        raise exception
            'TRNM native receipt event event_id sequence is already used by another column/default';
    end if;
    select coalesce(max(event_id), 0)
      into max_event_id
      from public.trnm_economic_receipt_events_v1;
    if max_event_id >= sequence_max then
        raise exception
            'TRNM native receipt event event_id sequence is exhausted';
    end if;
    if max_event_id > sequence_max - sequence_increment then
        raise exception
            'TRNM native receipt event event_id sequence is exhausted';
    end if;
    execute format(
        'select last_value::bigint, is_called from %s',
        sequence_qualified
    ) into sequence_last, sequence_called;
    if sequence_last is null
       or sequence_last < sequence_min
       or sequence_last < max_event_id
       or (sequence_last = max_event_id and not sequence_called) then
        raise exception
            'TRNM native receipt event event_id sequence is behind existing rows';
    end if;
    if sequence_last > sequence_max then
        raise exception
            'TRNM native receipt event event_id sequence is exhausted';
    end if;
    if sequence_called
       and sequence_last > sequence_max - sequence_increment then
        raise exception
            'TRNM native receipt event event_id sequence is exhausted';
    end if;
end
$native_event_id_sequence_guard$;

-- The row audit establishes that these columns are non-null for every
-- pre-existing event.  Promote that fact to structural NOT NULL constraints
-- so an empty/partially-created table cannot regress after this migration.
do $native_notnull_guard$
declare
    column_name text;
    column_notnull boolean;
begin
    foreach column_name in array array[
        'event_id', 'intent_id', 'event_sequence', 'intent_hash', 'receipt_id',
        'protocol_version', 'idempotency_scope', 'idempotency_key',
        'progression_class', 'status', 'amount_credits', 'receipt_json',
        'receipt_hash', 'event_kind', 'finalized_at', 'created_at'
    ]::text[]
    loop
        select a.attnotnull
          into column_notnull
          from pg_catalog.pg_attribute a
         where a.attrelid = 'public.trnm_economic_receipt_events_v1'::regclass
           and a.attname = column_name
           and not a.attisdropped;
        if not found then
            raise exception
                'TRNM native receipt event required column is missing: %', column_name;
        end if;
        if not column_notnull then
            execute format(
                'alter table public.trnm_economic_receipt_events_v1 alter column %I set not null',
                column_name
            );
        end if;
    end loop;
end
$native_notnull_guard$;

-- Add one independently-owned shape check for partial tables that were left
-- without the canonical named checks.  The semantic audit above has already
-- validated existing rows, so this is a regular (validated) constraint.  The
-- insert trigger continues to enforce cross-table intent bindings and JSON
-- evidence/hash equality that PostgreSQL CHECK expressions cannot express.
do $native_shape_constraint_guard$
begin
    -- A same-named CHECK may have been committed by an interrupted/manual
    -- rollout with an unreachable OR branch containing the canonical text (or
    -- with CHECK (true)).  Text-fragment matching cannot prove that every
    -- conjunct is live.  The semantic audit above has already validated every
    -- pre-existing row, so replace the object atomically under this migration's
    -- table lock.  This gives future direct SQL inserts the exact canonical
    -- predicate and makes a weakened same-named constraint fail closed instead
    -- of being mistaken for an authority check.
    if exists (
        select 1
          from pg_catalog.pg_constraint c
         where c.conrelid = 'public.trnm_economic_receipt_events_v1'::regclass
           and c.conname = 'trnm_receipt_events_native_shape_v1'
           and c.contype <> 'c'
    ) then
        raise exception
            'TRNM native receipt event shape object is not a CHECK constraint';
    end if;
    if exists (
        select 1
          from pg_catalog.pg_constraint c
         where c.conrelid = 'public.trnm_economic_receipt_events_v1'::regclass
           and c.conname = 'trnm_receipt_events_native_shape_v1'
           and c.contype = 'c'
    ) then
        alter table public.trnm_economic_receipt_events_v1
            drop constraint trnm_receipt_events_native_shape_v1;
    end if;

    alter table public.trnm_economic_receipt_events_v1
        add constraint trnm_receipt_events_native_shape_v1
        check (
            event_id > 0
            and
            event_sequence > 0
            and btrim(intent_id) <> ''
            and intent_hash ~ '^[0-9a-f]{64}$'
            and btrim(receipt_id) <> ''
            and btrim(protocol_version) <> ''
            and btrim(idempotency_scope) <> ''
            and btrim(idempotency_key) <> ''
            and progression_class in (
                'progression_allowed', 'recoverable_hold',
                'terminal_skip', 'hard_fail'
            )
            and length(btrim(status)) between 1 and 128
            and amount_credits >= 0
            and event_kind in ('initial', 'recoverable_hold_retry', 'progression')
            and jsonb_typeof(receipt_json) = 'object'
            and receipt_hash ~ '^[0-9a-f]{64}$'
        );
end
$native_shape_constraint_guard$;

