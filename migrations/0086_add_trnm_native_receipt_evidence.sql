    on public.trnm_economic_receipt_legacy_fallback_provenance_v1;

-- Reconcile every partially-created row, not only NULL/negative columns.  A
-- valid non-negative amount in the immutable intent is the authority; an
-- invalid/negative intent amount is fail-closed to zero (an explicit-NULL
-- intent amount follows the same fail-closed rule).  Only
-- when the intent truly omits amount_credits (the audit-only legacy shape) may
-- receipt evidence, then the already-stored non-negative projection, provide
-- a compatibility fallback.  This matters for an interrupted rollout where
-- the new column acquired its default `0` before the evidence backfill ran:
-- blindly trusting that zero would erase a real amount on the next retry.
with resolved_amounts as (
    select e.event_id,
           e.intent_id,
           e.receipt_id,
           e.protocol_version,
           e.status,
           e.progression_class,
           e.receipt_json,
           i.intent_json ->> 'term_id' as expected_term_id,
           extract(epoch from e.finalized_at)::bigint as expected_finalized_at_epoch,
           i.payload_hash,
           public.cex_trnm_nonnegative_jsonb_bigint_or_null_v1(
               e.receipt_json #> '{evidence,amount_credits}'
           ) as evidence_amount,
           coalesce(
               jsonb_typeof(e.receipt_json #> '{evidence}') = 'object'
                   and (e.receipt_json #> '{evidence}') ? 'amount_credits',
               false
           ) as evidence_amount_present,
           public.cex_trnm_nonnegative_bigint_or_null_v1(
               i.intent_json ->> 'amount_credits'
           ) as intent_amount,
           -- A present JSON null is distinct from an omitted key.  The native
           -- writer serializes Option::None as JSON null and emits zero
           -- evidence; treating that key as omitted here would let stale
           -- positive legacy evidence become value authority on retry.
           coalesce(i.intent_json ? 'amount_credits', false)
               as intent_amount_present,
           coalesce(
               (i.intent_json ? 'amount_credits')
                   and jsonb_typeof(i.intent_json -> 'amount_credits') = 'number'
                   and public.cex_trnm_nonnegative_bigint_or_null_v1(
                       i.intent_json ->> 'amount_credits'
                   ) is not null,
               false
           ) as intent_amount_valid,
           case when e.amount_credits >= 0 then e.amount_credits end as stored_amount
      from public.trnm_economic_receipt_events_v1 e
      join public.trnm_economic_intents i using (intent_id)
), chosen_amounts as (
    select *,
           case
               when intent_amount_valid then intent_amount
               when intent_amount_present then 0
               when evidence_amount is not null then evidence_amount
               -- A present-but-invalid evidence value (including a numeric
               -- string, decimal, negative, overflow, or JSON null) must not
               -- fall through to a previously stored positive value.  Only a
               -- genuinely absent evidence key may preserve that already
               -- persisted projection during an interrupted retry.
               when evidence_amount_present then 0
               else coalesce(stored_amount, 0)
           end as amount_credits
      from resolved_amounts
), normalized_rows as (
    select chosen_amounts.*,
           public.cex_trnm_normalize_receipt_json_v1(
               receipt_json,
               intent_id,
               receipt_id,
               protocol_version,
               expected_term_id,
               status,
               progression_class,
               payload_hash,
               amount_credits,
               expected_finalized_at_epoch
           ) as normalized_receipt_json
      from chosen_amounts
)
-- This pass runs after resolving immutable intent/evidence precedence, so an
-- existing default zero can never overwrite a valid immutable intent value.
update public.trnm_economic_receipt_events_v1 e
   set amount_credits = normalized_rows.amount_credits,
       receipt_json = normalized_rows.normalized_receipt_json,
       receipt_hash = encode(
           digest(normalized_rows.normalized_receipt_json::text, 'sha256'),
           'hex'
       )
  from normalized_rows
  join chosen_amounts chosen
    on chosen.event_id = normalized_rows.event_id
 where e.event_id = normalized_rows.event_id
   and (
       e.amount_credits is distinct from chosen.amount_credits
       or e.receipt_json is distinct from normalized_rows.normalized_receipt_json
       or e.receipt_hash is distinct from encode(
           digest(normalized_rows.normalized_receipt_json::text, 'sha256'),
           'hex'
       )
   );
alter table public.trnm_economic_receipt_events_v1
    alter column amount_credits set default 0,
    alter column amount_credits set not null;
do $constraint$
begin
    if not exists (
        select 1
          from pg_catalog.pg_constraint c
          join pg_catalog.pg_class t on t.oid = c.conrelid
          join pg_catalog.pg_namespace n on n.oid = t.relnamespace
         where n.nspname = 'public'
           and t.relname = 'trnm_economic_receipt_events_v1'
           and c.conname = 'trnm_receipt_events_amount_v1'
    ) then
        alter table public.trnm_economic_receipt_events_v1
            add constraint trnm_receipt_events_amount_v1 check (amount_credits >= 0);
    end if;
end
