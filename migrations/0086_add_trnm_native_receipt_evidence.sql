-- The amount/evidence backfill is the only compatibility repair in this
-- expand migration.  A previous attempt may already have installed the
-- append-only mutation guards before it was interrupted.  Drop those guards
-- inside this transaction while repairing legacy rows; if the transaction is
-- interrupted PostgreSQL rolls the drops back, and a retry starts safely.
drop trigger if exists trg_cex_reject_trnm_economic_receipt_event_mutation_v1
    on public.trnm_economic_receipt_events_v1;
