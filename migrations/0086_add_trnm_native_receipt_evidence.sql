begin;

-- migration-check: allow-destructive
-- Reviewed rollback posture: this migration is expand-only.  The marker is
-- required because PostgreSQL TRUNCATE triggers/privileges are mentioned in
-- the append-only guard; rollback never drops rows or disables the guards.

-- Native TRNM receipt snapshots are immutable evidence.  The legacy
-- trnm_economic_receipts row remains as a compatibility seed/projection; every
-- settlement attempt is recorded in this append-only event stream so a
-- recoverable hold can be retried without rewriting the original evidence.

create table if not exists public.trnm_economic_receipt_events_v1 (
    event_id bigint generated by default as identity primary key,
    intent_id text not null
        references public.trnm_economic_intents(intent_id)
        on delete restrict,
    event_sequence bigint not null,
    intent_hash text not null,
    receipt_id text not null,
    protocol_version text not null,
    idempotency_scope text not null,
    idempotency_key text not null,
    progression_class text not null,
    status text not null,
    amount_credits bigint not null default 0,
    receipt_json jsonb not null,
    receipt_hash text not null,
    event_kind text not null default 'initial',
    finalized_at timestamptz not null,
    created_at timestamptz not null default now(),
    constraint trnm_receipt_events_sequence_v1
        check (event_sequence > 0),
    constraint trnm_receipt_events_intent_hash_v1
        check (intent_hash ~ '^[0-9a-f]{64}$'),
    constraint trnm_receipt_events_receipt_hash_v1
        check (receipt_hash ~ '^[0-9a-f]{64}$'),
    constraint trnm_receipt_events_progression_v1
        check (progression_class in (
            'progression_allowed', 'recoverable_hold', 'terminal_skip', 'hard_fail'
        )),
    constraint trnm_receipt_events_status_v1
        check (length(btrim(status)) between 1 and 128),
    constraint trnm_receipt_events_amount_v1
        check (amount_credits >= 0),
    constraint trnm_receipt_events_event_kind_v1
        check (event_kind in ('initial', 'recoverable_hold_retry', 'progression')),
    constraint trnm_receipt_events_json_v1
        check (jsonb_typeof(receipt_json) = 'object'),
    constraint trnm_receipt_events_identity_v1
        unique (intent_id, event_sequence)
);

-- Check the existing authority rows independently of the constraint name.  A
-- partially-created table may already carry a same-named but weaker check;
-- malformed hashes must abort this transaction before any schema repair or
-- event row is backfilled.
do $intent_hash_guard$
begin
    if exists (
        select 1
          from public.trnm_economic_intents
         where payload_hash is null
            or payload_hash !~ '^[0-9a-f]{64}$'
    ) then
        raise exception 'TRNM economic intent payload_hash is not canonical';
    end if;
end
$intent_hash_guard$;

-- The native event stream is retained indefinitely with its intent authority.
-- Use an explicit RESTRICT action so a future change to the parent table can
-- never cascade-delete immutable evidence.  `CREATE TABLE IF NOT EXISTS` does
-- not retrofit that action on a table left behind by an interrupted runner;
-- the catalog guard below handles that boundary explicitly.
do $intent_hash_constraint$
begin
    if not exists (
        select 1
          from pg_catalog.pg_constraint c
         where c.conrelid = 'public.trnm_economic_intents'::regclass
           and c.conname = 'trnm_economic_intents_payload_hash_v1'
    ) then
        alter table public.trnm_economic_intents
            add constraint trnm_economic_intents_payload_hash_v1
            check (
                payload_hash is not null
                and payload_hash ~ '^[0-9a-f]{64}$'
            );
    end if;
end
$intent_hash_constraint$;

-- A partially-applied runner can leave the historical v1 constraint name in
-- place with a weaker expression.  Keep that name for compatibility, but add
-- a separately-owned canonical constraint so future intent rows remain
-- protected even when the old object was not ours to rewrite.  If a previous
-- attempt created the canonical name as NOT VALID, fail closed rather than
-- treating an unvalidated check as authority.
do $intent_hash_canonical_constraint$
declare
    constraint_validated boolean;
    constraint_expression text;
begin
    select c.convalidated,
           pg_get_expr(c.conbin, c.conrelid)
      into constraint_validated,
           constraint_expression
      from pg_catalog.pg_constraint c
     where c.conrelid = 'public.trnm_economic_intents'::regclass
       and c.contype = 'c'
       and c.conname = 'trnm_economic_intents_payload_hash_canonical_v1';
    if found then
        -- `CREATE TABLE IF NOT EXISTS` and an interrupted runner can leave a
        -- same-named but weaker check behind.  Checking only convalidated
        -- would accept `CHECK (payload_hash IS NOT NULL)` (or an always-true
        -- expression) as the canonical authority.  Compare PostgreSQL's
        -- normalized expression tree so harmless parenthesis/whitespace
        -- differences are ignored while predicate drift fails closed.
        if not constraint_validated
           or regexp_replace(
                  lower(coalesce(constraint_expression, '')),
                  '[[:space:]]+',
                  '',
                  'g'
              ) <> '((payload_hashisnotnull)and(payload_hash~''^[0-9a-f]{64}$''::text))' then
            raise exception 'TRNM economic intent canonical payload_hash constraint is not canonical';
        end if;
    else
        alter table public.trnm_economic_intents
            add constraint trnm_economic_intents_payload_hash_canonical_v1
            check (
                payload_hash is not null
                and payload_hash ~ '^[0-9a-f]{64}$'
            );
    end if;
end
$intent_hash_canonical_constraint$;

-- A manually committed/partially applied rollout may have created the event
-- table before its foreign key was installed.  Such a row cannot be
-- reconstructed from the compatibility receipt stream: accepting it would
-- leave an evidence event with no immutable intent authority and the inner
-- joins used by the compatibility backfill would silently skip it.  Fail
-- closed before any repair/backfill work, then restore the canonical FK when
-- the partial table is otherwise valid.
do $orphan_guard$
begin
    if exists (
        select 1
          from public.trnm_economic_receipt_events_v1 e
          left join public.trnm_economic_intents i
            on i.intent_id = e.intent_id
         where i.intent_id is null
    ) then
        raise exception 'TRNM receipt event intent binding does not exist';
    end if;
end
$orphan_guard$;

-- A receipt identity belongs to exactly one immutable intent.  The native
-- writer derives `receipt_id` from the intent identity, while retries append
-- additional event rows under that same id.  Detect a pre-existing cross-
-- intent fork before installing the first-event uniqueness index below.
do $receipt_identity_guard$
begin
    if exists (
        select 1
          from public.trnm_economic_receipt_events_v1
         group by receipt_id
        having count(distinct intent_id) > 1
    ) then
        raise exception 'TRNM native receipt history contains multiple intents for one receipt_id';
    end if;
    -- A compatibility seed is another immutable authority for the same
    -- receipt id.  Check it even when the pre-existing event stream has no
    -- sequence-one row (for example, an interrupted append).
    if exists (
        select 1
          from public.trnm_economic_receipt_events_v1 e
          join public.trnm_economic_receipts r
            on r.receipt_id = e.receipt_id
         where r.intent_id is distinct from e.intent_id
    ) then
        raise exception 'TRNM native receipt history conflicts with compatibility receipt intent';
    end if;
end
$receipt_identity_guard$;

-- `CREATE TABLE IF NOT EXISTS` does not retrofit key shape on a table left by
-- an independently committed/partially-run statement.  The runtime writer
-- omits event_id and derives the next (intent_id,event_sequence) pair, so a
-- nullable/duplicate/missing key would either make predecessor selection
-- ambiguous or allow concurrent writers to fork the stream.  Refuse such a
-- partial authority rather than proceeding with a table that cannot enforce
-- the append-only identity contract.  Both keys must be backed by a global,
-- ready and valid unique index (a primary-key index satisfies the event_id
-- check).
do $native_history_key_guard$
declare
    event_table oid := 'public.trnm_economic_receipt_events_v1'::regclass;
    event_attnum smallint;
    intent_attnum smallint;
    sequence_attnum smallint;
    event_type oid;
    intent_type oid;
    sequence_type oid;
    event_notnull boolean;
    intent_notnull boolean;
    sequence_notnull boolean;
    has_event_key boolean;
    has_intent_sequence_key boolean;
    duplicate_values boolean;
begin
    select a.attnum, a.atttypid, a.attnotnull
      into event_attnum, event_type, event_notnull
      from pg_catalog.pg_attribute a
     where a.attrelid = event_table
       and a.attname = 'event_id'
       and not a.attisdropped;
    select a.attnum, a.atttypid, a.attnotnull
      into intent_attnum, intent_type, intent_notnull
      from pg_catalog.pg_attribute a
     where a.attrelid = event_table
       and a.attname = 'intent_id'
       and not a.attisdropped;
    select a.attnum, a.atttypid, a.attnotnull
      into sequence_attnum, sequence_type, sequence_notnull
      from pg_catalog.pg_attribute a
     where a.attrelid = event_table
       and a.attname = 'event_sequence'
       and not a.attisdropped;

    if event_attnum is null or intent_attnum is null or sequence_attnum is null then
        raise exception 'TRNM native receipt event identity key columns are missing';
    end if;
    if event_type <> 'int8'::regtype
       or intent_type <> 'text'::regtype
       or sequence_type <> 'int8'::regtype then
        raise exception 'TRNM native receipt event identity key columns have incompatible types';
    end if;
    if not event_notnull or not intent_notnull or not sequence_notnull then
        raise exception 'TRNM native receipt event identity key columns must be NOT NULL';
    end if;

    execute format(
        'select exists (select 1 from public.trnm_economic_receipt_events_v1 where event_id is null)'
    ) into duplicate_values;
    if duplicate_values then
        raise exception 'TRNM native receipt event key contains a NULL event_id';
    end if;
    execute format(
        'select exists (select 1 from public.trnm_economic_receipt_events_v1 group by event_id having count(*) > 1)'
    ) into duplicate_values;
    if duplicate_values then
        raise exception 'TRNM native receipt event key contains duplicate event_ids';
    end if;
    execute format(
        'select exists (select 1 from public.trnm_economic_receipt_events_v1 where intent_id is null or event_sequence is null)'
    ) into duplicate_values;
    if duplicate_values then
        raise exception 'TRNM native receipt event key contains NULL intent/sequence values';
    end if;
    execute format(
        'select exists (select 1 from public.trnm_economic_receipt_events_v1 group by intent_id, event_sequence having count(*) > 1)'
    ) into duplicate_values;
    if duplicate_values then
        raise exception 'TRNM native receipt event key contains duplicate intent/sequence pairs';
    end if;

    select exists (
        select 1
          from pg_catalog.pg_index i
         where i.indrelid = event_table
           and i.indisunique
           and i.indisvalid
           and i.indisready
           and i.indimmediate
           and i.indpred is null
           and i.indnkeyatts = 1
           and i.indkey[0] = event_attnum
    ) into has_event_key;
    if not has_event_key then
        raise exception 'TRNM native receipt event_id key is missing a valid unique index';
    end if;

    select exists (
        select 1
          from pg_catalog.pg_index i
         where i.indrelid = event_table
           and i.indisunique
           and i.indisvalid
           and i.indisready
           and i.indimmediate
           and i.indpred is null
           and i.indnkeyatts = 2
           and i.indkey[0] = intent_attnum
           and i.indkey[1] = sequence_attnum
    ) into has_intent_sequence_key;
    if not has_intent_sequence_key then
        raise exception 'TRNM native receipt intent/sequence key is missing a valid unique index';
    end if;
end
$native_history_key_guard$;

-- Check the event-id generator before any compatibility backfill can attempt
-- an implicit insert.  A plain bigint key with no default would otherwise
-- survive the key audit and fail later with a misleading NULL violation.
do $native_event_id_default_presence_guard$
declare
    event_identity text;
    event_default text;
    event_default_oid oid;
begin
    select a.attidentity::text,
           coalesce(pg_get_expr(ad.adbin, ad.adrelid), ''),
           ad.oid
      into event_identity, event_default, event_default_oid
      from pg_catalog.pg_attribute a
      left join pg_catalog.pg_attrdef ad
        on ad.adrelid = a.attrelid
       and ad.adnum = a.attnum
     where a.attrelid = 'public.trnm_economic_receipt_events_v1'::regclass
       and a.attname = 'event_id'
       and not a.attisdropped;
    if event_identity is null then
        raise exception 'TRNM native receipt event event_id column is missing';
    end if;
    if coalesce(event_identity, '') = ''
       and event_default_oid is null then
        raise exception
            'TRNM native receipt event event_id has no identity or sequence default';
    end if;
    if coalesce(event_identity, '') = ''
       and regexp_replace(lower(event_default), '[[:space:]]+', '', 'g')
           !~ '^nextval\(.+\)$' then
        raise exception 'TRNM native receipt event event_id has an unsafe default';
    end if;
end
$native_event_id_default_presence_guard$;

-- Identity/serial defaults can still point at a sequence whose state lags
-- manually supplied event ids, or has already reached MAXVALUE.  Reconcile
-- that state before the compatibility INSERT and fail closed when no owned,
-- monotonic, non-cycling bigint sequence can produce the next key.
do $native_event_id_sequence_guard$
declare
    event_table oid := 'public.trnm_economic_receipt_events_v1'::regclass;
    event_attnum smallint;
    sequence_qualified text;
    sequence_oid oid;
    sequence_type oid;
    sequence_increment bigint;
    sequence_max bigint;
    sequence_min bigint;
    sequence_cycle boolean;
    sequence_last bigint;
    sequence_called boolean;
    max_event_id bigint;
begin
    select a.attnum
      into event_attnum
      from pg_catalog.pg_attribute a
     where a.attrelid = event_table
       and a.attname = 'event_id'
       and not a.attisdropped;
    if event_attnum is null then
        raise exception 'TRNM native receipt event event_id column is missing';
    end if;
    sequence_qualified := pg_get_serial_sequence(
        'public.trnm_economic_receipt_events_v1',
        'event_id'
    );
    if sequence_qualified is null then
        raise exception
            'TRNM native receipt event event_id default/identity has no owned sequence';
    end if;
    sequence_oid := to_regclass(sequence_qualified);
    if sequence_oid is null then
        raise exception 'TRNM native receipt event event_id sequence is missing';
    end if;
    select s.seqtypid, s.seqincrement, s.seqmax, s.seqmin, s.seqcycle
      into sequence_type, sequence_increment, sequence_max, sequence_min, sequence_cycle
      from pg_catalog.pg_sequence s
     where s.seqrelid = sequence_oid;
    if not found
       or sequence_type <> 'int8'::regtype
       or sequence_increment <= 0
       or sequence_min < 1
       or sequence_cycle then
        raise exception 'TRNM native receipt event event_id sequence is unsafe';
    end if;
    -- A sequence may be correctly owned by event_id and still be referenced
    -- by another column's DEFAULT nextval().  Such sharing lets unrelated
    -- writers consume the append key and causes ALTER/DROP ownership changes
    -- to break the other consumer.  Keep the generator private, excluding
    -- only this column's own attribute default (identity columns have none).
    if exists (
        select 1
          from pg_catalog.pg_depend d
          join pg_catalog.pg_attrdef ad on ad.oid = d.objid
         where d.classid = 'pg_catalog.pg_attrdef'::regclass
           and d.refclassid = 'pg_catalog.pg_class'::regclass
           and d.refobjid = sequence_oid
           and not (ad.adrelid = event_table and ad.adnum = event_attnum)
    ) then
        raise exception
            'TRNM native receipt event event_id sequence is already used by another column/default';
    end if;
    select coalesce(max(event_id), 0)
      into max_event_id
      from public.trnm_economic_receipt_events_v1;
    if max_event_id >= sequence_max then
        raise exception 'TRNM native receipt event event_id sequence is exhausted';
    end if;
    -- `nextval` advances by the sequence increment after a called sequence
    -- value.  A called sequence whose current value is only one increment
    -- below MAXVALUE is therefore already exhausted for the append path, even
    -- though the value itself is still below MAXVALUE.  An uncalled sequence
    -- returns its stored value once before advancing.  The subtraction is
    -- safe here: sequence_max is positive and sequence_increment is a
    -- positive bigint, so it cannot overflow a signed bigint in either
    -- direction.
    if max_event_id > sequence_max - sequence_increment then
        raise exception 'TRNM native receipt event event_id sequence is exhausted';
    end if;
    execute format(
        'select last_value::bigint, is_called from %s', sequence_qualified
    ) into sequence_last, sequence_called;
    -- An uncalled sequence returns its stored last_value on the next call,
    -- so MAXVALUE itself is still one valid candidate.  Once the value has
    -- been called, MAXVALUE (or any value without one full increment of
    -- headroom) is exhausted.
    if sequence_last is null
       or sequence_last < sequence_min
       or sequence_last > sequence_max
       or (sequence_last = sequence_max and sequence_called) then
        raise exception 'TRNM native receipt event event_id sequence is exhausted';
    end if;
    if sequence_called
       and sequence_last > sequence_max - sequence_increment then
        raise exception 'TRNM native receipt event event_id sequence is exhausted';
    end if;
    if sequence_last < max_event_id
       or (sequence_last = max_event_id and not sequence_called) then
        if max_event_id > 0 then
            -- `setval` is non-transactional.  RESTART is transactional, and
            -- restarting at max+increment preserves the old setval(..., true)
            -- semantics: the next generated id is strictly above every
            -- manually supplied event id.
            execute format(
                'alter sequence %s restart with %s',
                sequence_qualified,
                max_event_id + sequence_increment
            );
        else
            execute format(
                'alter sequence %s restart with %s',
                sequence_qualified,
                sequence_min
            );
        end if;
    end if;
end
$native_event_id_sequence_guard$;

do $foreign_key$
declare
    event_table oid := 'public.trnm_economic_receipt_events_v1'::regclass;
    intent_table oid := 'public.trnm_economic_intents'::regclass;
    event_intent_attnum smallint;
    intent_id_attnum smallint;
    canonical_fk_found boolean := false;
    safe_no_action_constraints text[] := array[]::text[];
    constraint_name text;
    fk record;
begin
    -- `create table if not exists` does not retrofit constraints when a
    -- deployment runner committed the table statement separately.  Detect a
    -- semantically equivalent single-column FK by catalog identity, and also
    -- require the immutable-retention semantics: validated, immediate,
    -- ON DELETE RESTRICT, ON UPDATE NO ACTION.  A pre-existing CASCADE,
    -- NOT-VALID, or deferred FK is rejected rather than silently retained.
    select a.attnum
      into event_intent_attnum
      from pg_catalog.pg_attribute a
     where a.attrelid = event_table
       and a.attname = 'intent_id'
       and not a.attisdropped;
    select a.attnum
      into intent_id_attnum
      from pg_catalog.pg_attribute a
     where a.attrelid = intent_table
       and a.attname = 'intent_id'
       and not a.attisdropped;
    if event_intent_attnum is null or intent_id_attnum is null then
        raise exception 'TRNM native receipt event intent foreign-key columns are missing';
    end if;

    for fk in
        select c.conname,
               c.convalidated,
               c.confdeltype,
               c.confupdtype,
               c.condeferrable,
               c.condeferred
          from pg_catalog.pg_constraint c
         where c.conrelid = event_table
           and c.contype = 'f'
           and c.confrelid = intent_table
           and c.conkey = array[event_intent_attnum]::smallint[]
           and c.confkey = array[intent_id_attnum]::smallint[]
    loop
        if not fk.convalidated
           or fk.condeferrable
           or fk.condeferred then
            raise exception 'TRNM native receipt event intent foreign key is not canonical (validated RESTRICT/immediate)';
        elsif fk.confdeltype = 'a'
              and fk.confupdtype = 'a' then
            -- PostgreSQL's immediate NO ACTION is equivalent to RESTRICT for
            -- this immutable parent, but the retention contract publishes an
            -- explicit RESTRICT action.  Repair this safe legacy shape inside
            -- the transaction; dangerous actions are never auto-repaired.
            safe_no_action_constraints := array_append(
                safe_no_action_constraints,
                fk.conname
            );
        elsif fk.confdeltype = 'r'
              and fk.confupdtype = 'a' then
            canonical_fk_found := true;
        else
            raise exception 'TRNM native receipt event intent foreign key is not canonical (validated RESTRICT/immediate)';
        end if;
    end loop;

    foreach constraint_name in array safe_no_action_constraints
    loop
        execute format(
            'alter table public.trnm_economic_receipt_events_v1 drop constraint %I',
            constraint_name
        );
    end loop;

    if not canonical_fk_found then
        alter table public.trnm_economic_receipt_events_v1
            add constraint trnm_receipt_events_intent_id_fkey_v1
            foreign key (intent_id)
            references public.trnm_economic_intents(intent_id)
            on delete restrict;
    end if;
end
$foreign_key$;

-- A unique first event serializes the receipt-id binding at the database
-- level.  `CREATE INDEX IF NOT EXISTS` compares only the relation name; an
-- interrupted/hand-authored rollout could leave that name attached to a
-- non-unique, partial, or differently-predicated index.  Validate the catalog
-- shape before accepting an existing object so the functional dependency
-- cannot be weakened silently.
do $native_initial_receipt_index_guard$
declare
    event_table oid := 'public.trnm_economic_receipt_events_v1'::regclass;
    receipt_attnum smallint;
    index_oid oid;
    canonical boolean := false;
    predicate text;
begin
    select a.attnum
      into receipt_attnum
      from pg_catalog.pg_attribute a
     where a.attrelid = event_table
       and a.attname = 'receipt_id'
       and not a.attisdropped;
    if receipt_attnum is null then
        raise exception 'TRNM native receipt event receipt_id column is missing';
    end if;

    select c.oid
      into index_oid
      from pg_catalog.pg_class c
      join pg_catalog.pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public'
       and c.relname = 'idx_trnm_receipt_events_receipt_id_initial_v1';
    if index_oid is not null then
        select i.indisunique
               and i.indisvalid
               and i.indisready
               and i.indimmediate
               and i.indpred is not null
               and i.indnkeyatts = 1
               and i.indkey[0] = receipt_attnum,
               regexp_replace(
                   lower(coalesce(pg_get_expr(i.indpred, i.indrelid), '')),
                   '[[:space:]]+',
                   '',
                   'g'
               )
          into canonical, predicate
          from pg_catalog.pg_index i
         where i.indexrelid = index_oid;
        if canonical is distinct from true
           or predicate is distinct from '(event_sequence=1)' then
            raise exception
                'TRNM native receipt initial receipt_id index is not canonical';
        end if;
    else
        create unique index idx_trnm_receipt_events_receipt_id_initial_v1
            on public.trnm_economic_receipt_events_v1(receipt_id)
            where event_sequence = 1;
    end if;
end
$native_initial_receipt_index_guard$;

create index if not exists idx_trnm_receipt_events_latest_v1
    on public.trnm_economic_receipt_events_v1(intent_id, event_sequence desc, event_id desc);

create index if not exists idx_trnm_receipt_events_finalized_v1
    on public.trnm_economic_receipt_events_v1(finalized_at desc, event_id desc);

-- An interrupted rollout may have created the event table before the amount column was added.
-- Make the upgrade path explicit and backfill only from immutable intent/evidence bytes; unknown
-- legacy amounts become zero and therefore fail closed at value-bearing consumers.
alter table public.trnm_economic_receipt_events_v1
    add column if not exists amount_credits bigint;

-- Do not turn an explicitly malformed JSON value into an apparently valid
-- empty object during the compatibility backfill.  Missing legacy evidence
-- fields are still repaired by the normalizer below, but a scalar/array root,
-- a non-object evidence node, or a typed identity field with the wrong JSON
-- type is an authority corruption and must abort the transaction before any
-- row is rewritten.  JSON null is treated as an absent optional value here;
-- the post-normalization guard below still requires the canonical bindings to
-- be present after repair.
do $native_json_shape_guard$
declare
    event_row record;
begin
    for event_row in
        select event_id, receipt_json
          from public.trnm_economic_receipt_events_v1
    loop
        if event_row.receipt_json is not null
           and jsonb_typeof(event_row.receipt_json) is distinct from 'object' then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: receipt_json is not an object';
        end if;
        if event_row.receipt_json is not null
           and event_row.receipt_json ? 'evidence'
           and jsonb_typeof(event_row.receipt_json -> 'evidence') is distinct from 'object'
           and jsonb_typeof(event_row.receipt_json -> 'evidence') is distinct from 'null' then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: evidence is not an object';
        end if;
        if event_row.receipt_json is not null
           and (
               (event_row.receipt_json ? 'intent_id'
                and jsonb_typeof(event_row.receipt_json -> 'intent_id') is distinct from 'null'
                and jsonb_typeof(event_row.receipt_json -> 'intent_id') <> 'string')
               or (event_row.receipt_json ? 'receipt_id'
                   and jsonb_typeof(event_row.receipt_json -> 'receipt_id') is distinct from 'null'
                   and jsonb_typeof(event_row.receipt_json -> 'receipt_id') <> 'string')
               or (event_row.receipt_json ? 'protocol_version'
                   and jsonb_typeof(event_row.receipt_json -> 'protocol_version') is distinct from 'null'
                   and jsonb_typeof(event_row.receipt_json -> 'protocol_version') <> 'string')
               or (event_row.receipt_json ? 'status'
                   and jsonb_typeof(event_row.receipt_json -> 'status') is distinct from 'null'
                   and jsonb_typeof(event_row.receipt_json -> 'status') <> 'string')
               or (event_row.receipt_json ? 'progression_class'
                   and jsonb_typeof(event_row.receipt_json -> 'progression_class') is distinct from 'null'
                   and jsonb_typeof(event_row.receipt_json -> 'progression_class') <> 'string')
           ) then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: JSON identity field has an incompatible type';
        end if;
        if event_row.receipt_json is not null
           and event_row.receipt_json #> '{evidence,payload_hash}' is not null
           and jsonb_typeof(event_row.receipt_json #> '{evidence,payload_hash}') is distinct from 'null'
           and (
               jsonb_typeof(event_row.receipt_json #> '{evidence,payload_hash}') <> 'string'
               or event_row.receipt_json #>> '{evidence,payload_hash}' !~ '^[0-9a-f]{64}$'
           ) then
            raise exception
                'TRNM native receipt history failed pre-existing-row validation: evidence payload_hash is invalid';
        end if;
    end loop;
end
